#-----------------------------------------------------------------------
# C string evaluation.
#
# A test entry's ciphertext is not always a bare literal: john writes
# {FORMAT_TAG "ce85b9..."} and relies on the preprocessor. So a literal is a
# SEQUENCE of tokens, each either a string literal or a macro that expands to
# one, and an unknown token makes the whole candidate unusable rather than
# partially usable. That refusal is the same rule derive-expressions.pl uses:
# silently dropping a token is how a wrong string proves itself.

# c_unescape($body) - the bytes a C string literal denotes, given its INSIDE.
sub c_unescape {
    my ($s) = @_;
    my $out = '';
    my $i   = 0;
    my $len = length $s;
    while ($i < $len) {
        my $ch = substr($s, $i, 1);
        if ($ch ne "\\") { $out .= $ch; $i++; next }
        my $esc = substr($s, $i + 1, 1);
        $i += 2;
        if    ($esc eq 'n') { $out .= "\n" }
        elsif ($esc eq 't') { $out .= "\t" }
        elsif ($esc eq 'r') { $out .= "\r" }
        elsif ($esc eq 'f') { $out .= "\f" }
        elsif ($esc eq 'b') { $out .= "\b" }
        elsif ($esc eq 'a') { $out .= "\a" }
        elsif ($esc eq 'v') { $out .= "\013" }
        elsif ($esc eq 'e') { $out .= "\033" }
        elsif ($esc eq 'x') {
            # \xNN.. is greedy in C; john never writes more than two digits.
            my $h = '';
            $h .= substr($s, $i++, 1) while $i < $len && substr($s, $i, 1) =~ /[0-9a-fA-F]/ && length($h) < 2;
            return undef unless length $h;
            $out .= chr(hex $h);
        }
        elsif ($esc =~ /[0-7]/) {
            my $o = $esc;
            $o .= substr($s, $i++, 1) while $i < $len && substr($s, $i, 1) =~ /[0-7]/ && length($o) < 3;
            $out .= chr(oct $o);
        }
        else { $out .= $esc }        # \\ \" \' and anything else: itself
    }
    return $out;
}

# str_expr($text, $defines) - evaluate a concatenation of literals and macros,
# or undef if any token is not one of those. $depth guards a macro cycle.
sub str_expr {
    my ($text, $defines, $depth) = @_;
    $depth //= 0;
    return undef if $depth > 8;
    my $out = '';
    my $any = 0;
    while ($text =~ /\G\s*(?:"((?:[^"\\]|\\.)*)"|(\w+))/gc) {
        if (defined $1) { my $v = c_unescape($1); return undef unless defined $v; $out .= $v }
        else {
            my $d = $defines->{$2};
            return undef unless defined $d;
            my $v = str_expr($d, $defines, $depth + 1);
            return undef unless defined $v;
            $out .= $v;
        }
        $any = 1;
    }
    # Anything left over (a cast, an arithmetic expression, a comment) means
    # this is not a plain string and must not be guessed at.
    return undef unless $any;
    return undef if $text =~ /\G\s*\S/gc;
    return $out;
}

