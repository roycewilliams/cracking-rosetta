# Verification. One hash, one word, a fresh pot, and --show's own count.

sub write_file {
    my ($path, @lines) = @_;
    open my $fh, '>', $path or die "$PROG: cannot write $path: $!\n";
    print {$fh} "$_\n" for @lines;
    close $fh;
    return $path;
}

sub run_capture {
    my ($secs, @argv) = @_;
    my $out = '';
    my $pid = open(my $fh, '-|');
    defined $pid or return (-1, '');
    if (!$pid) {
        open STDERR, '>&', \*STDOUT;
        exec { $argv[0] } @argv or exit 127;
    }
    my $killed = 0;
    eval {
        local $SIG{ALRM} = sub { $killed = 1; kill 'KILL', $pid; die "timeout\n" };
        alarm $secs;
        local $/;                       # slurp: $/ is the input record separator
        $out = <$fh> // '';
        alarm 0;
    };
    alarm 0;
    close $fh;
    return ($killed ? -2 : ($? >> 8), $out);
}

# ENC_REFUSAL is john refusing to run at all, and it looks exactly like a
# format that did not crack once the output is discarded:
#
#   This format does not yet support other encodings than ISO-8859-1
#
# john.c raises it for a format flagged FMT_UNICODE but not FMT_ENC whenever
# the configured encoding is neither raw nor ISO-8859-1, and this host's
# john.conf sets DefaultEncoding = UTF-8 (line 274). It is a fact about the
# host's configuration, not about the entry's label: dynamic_1507 passes its
# own --test=0 and cracks its own published vector the moment the encoding is
# named on the command line.
#
# The retry is offered ONLY when john printed that line AND the plaintext is
# pure ASCII, where UTF-8 and ISO-8859-1 are byte-for-byte the same input and
# the flag therefore cannot change what was proven. On a non-ASCII plaintext
# the two encodings feed the format different bytes, so a crack under the flag
# would be a claim about a different string; that case is reported, not retried.
my $ENC_REFUSAL = 'does not yet support other encodings';
my $ENC_FLAG    = '--input-encoding=iso-8859-1 ';

# crack($label, $hash, $pass, $tab) - did john recover $pass from $hash under
# $label? $tab picks the reading scheme: a synthetic login and a tab separator,
# which is what verify-vectors.pl uses, or the bare line handed over natively.
# Returns (ok, reason, encoding-flag-needed).
sub crack {
    my ($label, $hash, $pass, $tab, $tag) = @_;
    my $jbin = basename($john);
    (my $safe = "$tag.$label") =~ s/[^A-Za-z0-9._-]/_/g;
    my $hf  = write_file("$workdir/$safe.hash", $tab ? "v0\t$hash" : $hash);
    my $wf  = write_file("$workdir/$safe.word", $pass);
    my $pot = "$workdir/$safe.pot";
    my $sep = $tab ? '--field-separator-char=tab ' : '';

    for my $enc ('', $ENC_FLAG) {
        unlink $pot;

        # Run from run/ -- john resolves john.conf against the cwd -- with the
        # pot and the session in the work dir, which is writable when run/ is
        # not. john exits 1 with NO message when it cannot write john.log,
        # which is indistinguishable from "did not crack", so --session must
        # land here. stderr is KEPT rather than discarded, because the whole
        # point of the retry is a refusal that only shows up there.
        my ($code, $out) = run_capture($timeout, '/bin/sh', '-c',
            sprintf('cd %s && ./%s --format=%s %s%s--wordlist=%s --pot=%s --session=%s %s 2>&1 >/dev/null',
                    quotemeta($jdir), quotemeta($jbin), quotemeta($label), $sep, $enc,
                    quotemeta($wf), quotemeta($pot), quotemeta("$workdir/$safe"),
                    quotemeta($hf)));
        return (0, 'timeout', 0) if $code == -2;

        if (index($out, $ENC_REFUSAL) >= 0) {
            next if !length $enc && $pass !~ /[^\x20-\x7e]/;
            return (0, 'refused: needs ISO-8859-1 and the plaintext is not ASCII', 0)
                if !length $enc;
            return (0, 'refused on the encoding even with the flag', 0);
        }

        my (undef, $shown) = run_capture($timeout, '/bin/sh', '-c',
            sprintf('cd %s && ./%s --show --format=%s %s%s--pot=%s %s 2>/dev/null',
                    quotemeta($jdir), quotemeta($jbin), quotemeta($label), $sep, $enc,
                    quotemeta($pot), quotemeta($hf)));

        # One hash in, one word in: john's own tally is unambiguous, and it
        # avoids both --show reading traps (the plaintext is not always the
        # last field, and a field-wise match on a common plaintext can
        # coincide).
        return (1, '', (length $enc ? 1 : 0))
            if ($shown // '') =~ /^(\d+) password hash(?:es)? cracked/m && $1 > 0;
        last unless length $enc;      # no refusal seen: the flag changes nothing
    }
    return (0, 'not cracked', 0);
}

#-----------------------------------------------------------------------
# Targets: entries with no vector at all that name a john identifier we have
# an example for.

my $nsrc = load_source();
index_labels();
my $ndyn = load_dynamic_conf();
printf STDERR "%s: %d john source file(s), %d fmt_tests array(s), %d label(s) resolved, %d dynamic.conf Test= line(s)\n",
    $PROG, $nsrc, scalar keys %array, scalar keys %tests_of, $ndyn if $verbose;

opendir(my $dh, $algdir) or do { print STDERR "$PROG: cannot read $algdir: $!\n"; exit 1 };
my @files = sort grep { /\.yaml$/ } readdir $dh;
closedir $dh;

my (@cand, @noscore);
my $targets = 0;

for my $f (@files) {
    my $path = "$algdir/$f";
    my $e = eval { YAML::XS::LoadFile($path) };
    unless ($e) { print STDERR "$PROG: cannot load $path: $@\n"; exit 1 }
    my $id = $e->{id} // ($f =~ s/\.yaml$//r);
    next if %only && !$only{$id};
    next if ($e->{status} // '') eq 'merged';
    next if $e->{vectors} && @{ $e->{vectors} };
    my @labels = (@{ $e->{tools}{john}{cpu} || [] }, @{ $e->{tools}{john}{gpu} || [] });
    next unless @labels;
    $targets++;

    my @c;
    for my $label (@labels) {
        if ($label =~ /^dynamic_\d+$/i) {
            for my $t (dyn_candidates($label)) {
                push @c, { id => $id, path => $path, entry => $e, label => $label,
                           route => ($t->{transcoded} ? 'dynamic.conf (transcoded)'
                                                      : 'dynamic.conf'),
                           hash => $t->{hash}, pass => $t->{pass} };
            }
        }
        my $t = $tests_of{ lc $label } or next;
        for my $x (examples_from_array(@$t)) {
            push @c, { id => $id, path => $path, entry => $e, label => $label,
                       route => "fmt_tests ($t->[3])",
                       hash => $x->{hash}, pass => $x->{pass} };
        }
    }
    # A plaintext john cannot put in a wordlist proves nothing: an empty one
    # and one carrying a newline are both unusable as a candidate line.
    @c = grep { length $_->{pass} && $_->{pass} !~ /[\r\n]/ && $_->{hash} !~ /[\r\n]/ } @c;
    if (@c) { push @cand, \@c }
    else    { push @noscore, $id }
}

#-----------------------------------------------------------------------
# Run. Each entry gets its candidates tried in order until one verifies: the
# first is not always loadable (a test array can hold several serializations)
# and one that john reads is worth more than the one that came first.

my $started = time;
my (@ok, @bad);
my $n = 0;

printf "# %s -- %d target entr%s with no vector naming a john identifier; %d with an example, %d without\n",
    $PROG, $targets, ($targets == 1 ? 'y' : 'ies'), scalar @cand, scalar @noscore;
print "# columns: result, entry, label, route, scheme, hash, pass\n";

for my $set (@cand) {
    last if $limit && $n >= $limit;
    $n++;

    if ($dry) {
        my $c = $set->[0];
        printf "PLAN\t%s\t%s\t%s\t-\t%s\t%s\n",
            $c->{id}, $c->{label}, $c->{route}, $c->{hash}, $c->{pass};
        next;
    }

    my ($won, $why);
    for my $c (@$set) {
        for my $tab (1, 0) {
            my ($good, $reason, $enc) = crack($c->{label}, $c->{hash}, $c->{pass}, $tab, $c->{id});
            if ($good) {
                $c->{scheme} = ($tab ? 'tab' : 'native') . ($enc ? '+iso8859-1' : '');
                $won = $c;
                last;
            }
            $why = $reason;
        }
        last if $won;
    }

    my $first = $set->[0];
    printf STDERR "-   %-46s %-24s %s\n", $first->{id}, $first->{label},
        ($won ? "verified ($won->{scheme}, $won->{route})" : "FAILED ($why)")
        if $verbose;

    if ($won) {
        push @ok, $won;
        printf "OK\t%s\t%s\t%s\t%s\t%s\t%s\n",
            $won->{id}, $won->{label}, $won->{route}, $won->{scheme},
            $won->{hash}, $won->{pass};
    }
    else {
        push @bad, $first;
        printf "FAIL\t%s\t%s\t%s\t-\t%s\t%s\n",
            $first->{id}, $first->{label}, $first->{route},
            $first->{hash}, $first->{pass};
    }
}

print "SKIP\t$_\t-\t-\t-\t-\t-\n" for @noscore;

#-----------------------------------------------------------------------
# Write. Only the verified ones, and only under --apply.

my $written = 0;
if ($apply) {
    my %touched;
    for my $c (@ok) {
        push @{ $c->{entry}{vectors} }, {
            hash   => $c->{hash},
            pass   => $c->{pass},
            source => 'john',
        };
        $touched{ $c->{path} } = $c->{entry};
    }
    $written += emit_entry($_, $touched{$_}) for sort keys %touched;
}

my $elapsed = time - $started;
printf STDERR "%s: %d entr%s examined, %d verified, %d failed, %d file(s) written in %.1fs\n",
    $PROG, $n, ($n == 1 ? 'y' : 'ies'), scalar @ok, scalar @bad, $written, $elapsed;

if (@bad) {
    printf STDERR "%s: a failure is evidence about the entry's john label, not just about the example -- review the FAIL rows.\n", $PROG;
}
if ($apply && $written) {
    printf STDERR "%s: tiers untouched. Promote what is now provable with:\n    ./tools/verify-vectors.pl --tool john -v\n", $PROG;
}

exit 0;
