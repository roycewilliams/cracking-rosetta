#!/usr/bin/perl
#
# seed-john-vectors.pl -- give an entry that has no test vector one that john
# itself publishes, and prove it by cracking it.
#
# WHY THIS EXISTS
#
# 54 entries carry no vector at all, so nothing about them can ever reach tier
# 'vector' for ANY tool: every tier above 'asserted' is a round-trip and a
# round-trip needs a hash and a plaintext. seed-vectors.pl already reads the
# published example out of data/tools/mdxfind.yaml and data/tools/hashcat.yaml.
# It cannot reach these, and CLAUDE.md says why: john's --list=format-details
# TRUNCATES example_ciphertext at 896 characters with no marker at all, and
# every container format's example is a whole volume header, so the extractor
# that built data/tools/john.yaml never saw a loadable hash for them.
#
# john's own source does carry them, in full:
#
#   route 1  static struct fmt_tests <name>[] in src/*.c, entries of the shape
#            { "<ciphertext>", "<plaintext>" }.  28 of the 54.
#   route 2  Test= lines in run/dynamic.conf, "<ciphertext>:<plaintext>[:<login>]",
#            for the config-defined dynamics that have no C file.  8 of the 54.
#
# WHY THE SOURCE IS NOT THE PROOF
#
# CLAUDE.md's rule for exactly this: the source PROPOSES and john's crack
# PROVES. So every candidate harvested here is handed back to john under the
# label THIS entry names, against a wordlist holding nothing but the candidate
# plaintext, and is stored only if john recovers it. A test array is evidence
# about the array; it is not evidence that this entry's john label is the one
# that computes it, and that second claim is the whole reason the entry exists.
#
# One hash and one word per invocation, so `--show`'s own "N password hash(es)
# cracked" is the signal. That sidesteps two recorded traps at once: --show
# does not always put the plaintext last (it re-inserts a login into the
# original line structure instead), and a field-wise match on a common
# plaintext can coincide. With a single-line hash file and a single-word
# wordlist there is only one thing john can have cracked.
#
# WHY IT REFUSES A CANDIDATE THAT NEEDS A LOGIN FIELD
#
# A vector stored here has to be re-provable by verify-vectors.pl, which writes
# a SYNTHETIC login before every hash. So a ciphertext that only cracks when a
# particular login sits beside it would verify once here and never again. Where
# the source line carries a login, this tool transcodes it into john's own
# self-contained spelling -- ciphertext . '$$U' . login, which dynamic_1401's
# own Test= lines demonstrate upstream -- and proves THAT string under a
# synthetic login. A wrong transcode fails to load or fails to crack, which is
# the standard CLAUDE.md requires of a transcode. Nothing is stored otherwise.
#
# WHY TWO READING SCHEMES
#
# --field-separator-char governs READING, not just printing, so the tab scheme
# cannot work for a format whose ciphertext EMBEDS its own login: NETLM,
# NetHalfLM, MSCHAPv2 and NetNTLM all put USER::DOMAIN: at the front, and
# displacing that field is exactly what breaks the parse. Such a format is
# handed the bare line natively instead. The tab scheme is tried first because
# it is the one verify-vectors.pl uses, so a candidate that only passes
# natively is reported as such.
#
# WHAT IT NEVER DOES
#
# It never touches a `verified:` tier -- verify-vectors.pl owns those, and
# keeping promotion in one place is what stops a seed pass from promoting its
# own seed. It never replaces a vector an entry already carries.
#
# DEPENDENCIES: YAML::XS, tools/lib/RosettaEmit.pm, a jumbo john binary and a
# readable john source tree. Run from anywhere; paths resolve against the repo.
#
# Generated by Claude Opus 5 on 2026-09-04

