# john's source: every fmt_tests array, and which FORMAT_LABEL uses which.

# skip_to_close($txt, $i) - $i is at '{'; return the index of its match, with
# strings, char constants and both comment styles stepped over.
sub skip_to_close {
    my ($txt, $i) = @_;
    my $len   = length $txt;
    my $depth = 0;
    while ($i < $len) {
        my $ch = substr($txt, $i, 1);
        my $two = substr($txt, $i, 2);
        if ($two eq '/*') { my $e = index($txt, '*/', $i + 2); $i = $e < 0 ? $len : $e + 2; next }
        if ($two eq '//') { my $e = index($txt, "\n", $i);     $i = $e < 0 ? $len : $e + 1; next }
        if ($ch eq '"' || $ch eq "'") {
            my $q = $ch; $i++;
            while ($i < $len) {
                my $c = substr($txt, $i, 1);
                last if $c eq $q;
                $i += ($c eq "\\") ? 2 : 1;
            }
            $i++;
            next;
        }
        $depth++ if $ch eq '{';
        if ($ch eq '}') { $depth--; return $i if $depth == 0 }
        $i++;
    }
    return -1;
}

# split_top($body) - split on commas at brace depth 0, strings respected.
sub split_top {
    my ($body) = @_;
    my (@out, $cur, $depth);
    $cur = ''; $depth = 0;
    my $i = 0; my $len = length $body;
    while ($i < $len) {
        my $ch  = substr($body, $i, 1);
        my $two = substr($body, $i, 2);
        if ($two eq '/*') { my $e = index($body, '*/', $i + 2); $i = $e < 0 ? $len : $e + 2; next }
        if ($two eq '//') { my $e = index($body, "\n", $i);     $i = $e < 0 ? $len : $e + 1; next }
        if ($ch eq '"' || $ch eq "'") {
            my $q = $ch; my $s = $i; $i++;
            while ($i < $len) {
                my $c = substr($body, $i, 1);
                last if $c eq $q;
                $i += ($c eq "\\") ? 2 : 1;
            }
            $i++;
            $cur .= substr($body, $s, $i - $s);
            next;
        }
        $depth++ if $ch eq '{' || $ch eq '(';
        $depth-- if $ch eq '}' || $ch eq ')';
        if ($ch eq ',' && $depth == 0) { push @out, $cur; $cur = ''; $i++; next }
        $cur .= $ch;
        $i++;
    }
    push @out, $cur;
    return @out;
}

my (%text, %defines, %array, %arrays_named);

sub load_source {
    opendir(my $dh, $src) or do {
        print STDERR "$PROG: cannot read john source $src: $!\n"; exit 1;
    };
    my @files = sort grep { /\.(?:c|h)$/ } readdir $dh;
    closedir $dh;

    for my $f (@files) {
        open my $fh, '<:raw', "$src/$f" or next;
        local $/;
        my $txt = <$fh>;
        close $fh;
        $text{$f} = $txt;

        # Object-like #defines whose body starts a string or a macro name. A
        # trailing comment is stripped; a function-like macro is skipped.
        my %d;
        while ($txt =~ /^[ \t]*#[ \t]*define[ \t]+(\w+)[ \t]+([^\n]*)$/mg) {
            my ($name, $body) = ($1, $2);
            $body =~ s{/\*.*}{};
            $body =~ s{//.*}{};
            $body =~ s/\s+$//;
            next unless $body =~ /^\s*(?:"|\w+\s*")/;
            $d{$name} = $body;
        }
        $defines{$f} = \%d;

        while ($txt =~ /struct\s+fmt_tests\s+(\w+)\s*\[\s*\]\s*=\s*/g) {
            my $name = $1;
            my $open = index($txt, '{', pos $txt);
            next if $open < 0;
            my $close = skip_to_close($txt, $open);
            next if $close < 0;
            $array{"$f\0$name"} = substr($txt, $open + 1, $close - $open - 1);
            push @{ $arrays_named{$name} }, $f;
        }
    }
    return scalar @files;
}

# index_labels() - which fmt_tests array each john format label uses.
#
# Read from the format struct itself rather than from the file, because
# neither half of the pairing is where a first pass would look for it.
#
#   struct fmt_main fmt_haval_128_4 = {
#       {
#           "HAVAL-128-4",        <- the label, and NOT always a FORMAT_LABEL
#           ...                      #define: a file defining several formats
#           haval_128_4_tests     <- the tests array, last member of the
#       }, {                         params struct
#
# Two things this gets right that a per-file heuristic does not. A file can
# hold SEVERAL fmt_main structs with a string literal for each label
# (haval_fmt_plug.c, ripemd_fmt_plug.c, truecrypt_fmt_plug.c all do), so
# scanning for #define FORMAT_LABEL misses every one of them. And the array is
# not always in the same file: john keeps a container format's tests in
# <name>_common_plug.c, and wpapsk_fmt_plug.c gets its `tests` from the
# wpapsk.h it includes. So resolution follows the identifier -- this file
# first, then the files this file #includes, then the unique file in the tree
# that defines it. A name defined in several files and included by none of
# them is refused rather than guessed at: john's file-local `tests` is
# declared in dozens of plugins and picking one would be a coin toss.
my %tests_of;

sub index_labels {
    for my $f (sort keys %text) {
        my $txt = $text{$f};
        my $d   = $defines{$f} || {};

        # Files this one includes by name, in order, for the array lookup.
        my @inc = $txt =~ /^[ \t]*#[ \t]*include[ \t]+"([^"]+)"/mg;

        while ($txt =~ /struct\s+fmt_main\s+\w+\s*=\s*/g) {
            my $open = index($txt, '{', pos $txt);
            next if $open < 0;
            my $close = skip_to_close($txt, $open);
            next if $close < 0;
            # The first top-level element of the fmt_main initialiser is the
            # whole params struct; the label and the tests identifier are its
            # first and last members.
            my ($pa) = split_top(substr($txt, $open + 1, $close - $open - 1));
            my $po = index($pa, '{');
            next if $po < 0;
            my $pc = skip_to_close($pa, $po);
            next if $pc < 0;
            my @member = split_top(substr($pa, $po + 1, $pc - $po - 1));
            next if @member < 2;

            my $label = str_expr($member[0], $d);
            next unless defined $label && length $label;

            # The tail can carry #endif lines; the identifier is the last bare
            # word in it.
            my @word = $member[-1] =~ /([A-Za-z_]\w*)/g;
            next unless @word;
            my $id = $word[-1];

            my $owner;
            if (exists $array{"$f\0$id"}) { $owner = $f }
            else {
                for my $h (@inc) { next unless exists $array{"$h\0$id"}; $owner = $h; last }
                unless (defined $owner) {
                    my $o = $arrays_named{$id};
                    $owner = $o->[0] if $o && @$o == 1;
                }
            }
            next unless defined $owner;
            # The array's own file and the file that names it BOTH contribute
            # macros: a test entry written {FORMAT_TAG "..."} takes FORMAT_TAG
            # from wherever it is defined, which is not always where the array
            # sits.
            $tests_of{ lc $label } //= [ $array{"$owner\0$id"},
                                         $defines{$owner} || {}, $d, "$owner:$id" ];
        }
    }
}

# examples_from_array($body, $defs_a, $defs_b, $where) - the
# { ciphertext, plaintext } pairs that evaluate to plain strings, in source
# order. Two define tables are consulted, the array's file and the naming
# file's, in that order.
#
# #if is NOT evaluated, so a conditionally compiled array yields the UNION of
# its branches: wpapsk.h holds one `tests` whose #ifdef WPAPMK half carries
# PMK plaintexts and whose #else half carries passphrases, and both halves
# come back here. That is safe only because john is the oracle -- a pair from
# the branch this build did not compile simply fails to crack and the next
# candidate is tried. It would NOT be safe in a tool that believed the source.
sub examples_from_array {
    my ($body, $da, $db) = @_;
    my $d = { %{ $db || {} }, %{ $da || {} } };
    my @out;
    my $i = 0;
    my $len = length $body;
    while ($i < $len) {
        my $open = index($body, '{', $i);
        last if $open < 0;
        my $close = skip_to_close($body, $open);
        last if $close < 0;
        my $rec = substr($body, $open + 1, $close - $open - 1);
        $i = $close + 1;
        my @field = split_top($rec);
        next if @field < 2;
        # A third element is fields[], which carries a login john needs beside
        # the hash. That cannot be stored self-contained, so it is skipped.
        next if @field > 2 && $field[2] =~ /\S/;
        my $hash = str_expr($field[0], $d);
        my $pass = str_expr($field[1], $d);
        next unless defined $hash && defined $pass;
        push @out, { hash => $hash, pass => $pass };
    }
    return @out;
}

#-----------------------------------------------------------------------
# dynamic.conf: Test=<ciphertext>:<plaintext>[:<login>]
#
# A line with a login is transcoded to john's self-contained spelling before it
# is offered, and only where the ciphertext does not already carry one. The
# 2-field lines are preferred, so the transcode is a fallback rather than the
# usual path.

my %dyn_tests;

sub load_dynamic_conf {
    open my $fh, '<:raw', $conf or do {
        print STDERR "$PROG: cannot read $conf: $!\n"; return 0;
    };
    my $section = '';
    my $n = 0;
    while (my $line = <$fh>) {
        $line =~ s/\r?\n$//;
        if ($line =~ /^\[List\.Generic:(dynamic_\d+)\]/i) { $section = lc $1; next }
        next unless $section;
        next unless $line =~ /^Test=(.*)$/;              # TestM=/TestF= are
        my $rest = $1;                                   # length-probe variants
        my @f = split /:/, $rest;
        next if @f < 2;
        my ($hash, $pass, $login) = ($f[0], $f[1], (@f > 2 ? join(':', @f[2 .. $#f]) : undef));
        next unless length $hash && length $pass;
        push @{ $dyn_tests{$section} }, { hash => $hash, pass => $pass, login => $login };
        $n++;
    }
    close $fh;
    return $n;
}

# dyn_candidates($label) - self-contained ciphertexts for a dynamic, best first.
sub dyn_candidates {
    my ($label) = @_;
    my @out;
    for my $t (@{ $dyn_tests{ lc $label } || [] }) {
        push @out, { hash => $t->{hash}, pass => $t->{pass}, transcoded => 0 }
            unless defined $t->{login};
    }
    for my $t (@{ $dyn_tests{ lc $label } || [] }) {
        next unless defined $t->{login} && length $t->{login};
        next if $t->{hash} =~ /\$\$U/;            # already self-contained
        push @out, { hash => "$t->{hash}\$\$U$t->{login}", pass => $t->{pass},
                     transcoded => 1 };
    }
    return @out;
}

