# hav128_4 / hav160_5 / ... expand mechanically
for my $w (qw(128 160 192 224 256)) {
    for my $r (3, 4, 5) { $FUNC{"hav${w}_$r"} = "haval${w}_$r" }
}
# _bin is this repository's _raw
for my $k (keys %FUNC) {
    $FUNC{"${k}_bin"} = "$FUNC{$k}_raw" if $k =~ /^(md|sha|wrl|gost|rmd|sne|hav)/;
}
$FUNC{utf16le} = 'utf16';

