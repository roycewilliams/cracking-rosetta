package RosettaHx;
#-----------------------------------------------------------------------
#
# Name: RosettaHx
# Description: read Appendix A of the hx Language Specification and decide
#              what this repository may say about each mdxfind type
#
#-----------------------------------------------------------------------
# METHODOLOGY AND WHY THIS EXISTS
#
# Appendix A of the hx Language Specification (Waffle, rev 1.15, Aug 2026)
# states an hx expression for 1011 mdxfind types. Two tools consume it and
# they must agree, because they write MUTUALLY EXCLUSIVE fields: seed-hx.pl
# writes expression:, denote-hx.pl writes denotation:, and validate.pl fails
# an entry carrying both. Two private copies of "is this expressible here"
# would eventually disagree, and the day they do an entry says the same thing
# twice at two strengths. So the boundary lives here, once.
#
# The specification is NOT vendored: this repository is MIT throughout and the
# PDF carries no licence grant. Re-fetch it to tmp/hx/ to re-run either tool.
#
# WHAT THE BOUNDARY IS
#
# %FUNC is the set of hx function tokens this repository knows how to spell in
# an expression:. A candidate naming anything outside it is NOT partially
# translated -- it is refused whole. Dropping a token silently is how
# md5(md5($p).":".$u) once looked like md5(md5($p).$s), and how cap() -- a
# no-op on a lowercase digest -- can make a wrong expression "prove" itself.
#
# The complement is what makes denotation: a checkable fact rather than a
# shrug: pbkdf2_sha256(), bcrypt(), blake2b512(), groestl256() name functions
# john's dynamic EXPRESSION language does not have, so those types have no
# expression here and never will. That is a lookup, not an opinion. Note what
# it does NOT say: john has FORMATS for bcrypt and for HMAC-SHA1.
#
# TWO PARSE DEFECTS THIS FIXES, both found 2026-08-31 by bucketing the 309
# types seed-hx.pl was refusing under one undifferentiated label:
#
#   1. The trailing prose gloss. Appendix A appends explanations to some
#      expressions -- "sha1(fromhex(salt) . pass) (macOS 10.4-10.6; salt is
#      hex-decoded)". The first stripper required the gloss to begin with a
#      capital, so a lowercase one survived into the expression, and its ';'
#      and '=' then made the whole type look like a multi-statement hx program.
#      Five types were lost that way, three of them (MACOSX, POSTGRESCRAM,
#      WINPHONE) perfectly translatable. strip_gloss() instead finds the
#      trailing parenthesised group and takes it only when what precedes it is
#      itself a complete balanced expression -- so md5(pass) is never mistaken
#      for a gloss, and the gloss is kept rather than discarded.
#
#   2. PDF typography. The PDF renders hx's iteration operator as U+02C6
#      MODIFIER LETTER CIRCUMFLEX, so the extracted text carries
#      "sha512^65536(...)" spelled with a non-ASCII lookalike -- and a
#      consumer of dist/rosetta.csv grepping for '^' does not find it. En and
#      em dashes and curly quotes come through the same way. All of it is
#      typesetting rather than content, so ascii_fold() flattens it on the way
#      in. This is not cosmetic: the corpus was 100% ASCII until an en dash
#      from a gloss reached one entry on 2026-08-31, and fmt.pl's
#      render-and-reparse check failed on it immediately, because YAML::XS
#      wants UTF-8 octets and had been handed decoded characters.
#
# MULTI-EMIT IS TWO LISTS, NOT ONE
#
# Note [24] names 34 types that emit SEVERAL candidate digests per input and
# match if any one reproduces the stored hash; such a type has no single
# expression, so writing one is a false claim even when the string is one of
# the forms. Appendix A ALSO spells emit() in the expression for 14 further
# types, and the two sets are disjoint -- measured 2026-08-31. So the note is
# not the whole population and must not be treated as one. is_multi_emit()
# answers from both.
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-08-31

use strict;
use warnings;
use Exporter qw(import);

our @EXPORT_OK = qw(parse_appendix translate_hx strip_gloss ascii_fold
                    is_multi_emit %FUNC);

#-----------------------------------------------------------------------
# hx spelling -> this repository's spelling. A token absent from here is a
# token neither tool will translate.

our %FUNC = (
    md5 => 'md5', md4 => 'md4', md2 => 'md2',
    sha1 => 'sha1', sha0 => 'sha0', sha224 => 'sha224', sha256 => 'sha256',
    sha384 => 'sha384', sha512 => 'sha512',
    wrl => 'whirlpool', gost => 'gost',
    rmd128 => 'ripemd128', rmd160 => 'ripemd160',
    rmd256 => 'ripemd256', rmd320 => 'ripemd320',
    sne128 => 'snefru128', sne256 => 'snefru256',
    hav128 => 'haval128_3', hav160 => 'haval160_3',
    hav192 => 'haval192_3', hav224 => 'haval224_3', hav256 => 'haval256_3',
    # representation modifiers that carry over unchanged in meaning
    upper => 'upper', lower => 'lower', cap => 'cap', rev => 'rev',
    base64 => 'base64', hex => 'hex',
    # structural, and descriptive rather than cryptographic. These cannot be
    # compiled by john, so an expression using one stays at tier upstream --
    # but the field is documented as hx-style, and ciscoasa already carries a
    # pad(). Refusing them would lose real information for no gain, and
    # denote-hx.pl must therefore NOT count them as grounds for `absent`.
    cut => 'cut', pad => 'pad', fromhex => 'fromhex',
    frombase64 => 'frombase64', utf16be => 'utf16be',
