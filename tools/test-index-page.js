//-----------------------------------------------------------------------
// METHODOLOGY AND WHY THIS EXISTS
//
// docs/index.html is the front door: for anyone who is not reading the
// repository it IS the project. Its behavior is generated by render.pl as a
// string, so a wrong selector or a mistyped array index is invisible to
// perl -c, to validate.pl and to `node --check` alike -- all three pass on a
// page whose search finds nothing.
//
// So this stubs just enough DOM to run the page's own render() and
// focusHash(), then asserts the things a reader depends on: every row carries
// its entry id, the permalink points at it, a merged-away id resolves to its
// survivor with a note, and a search finds a row by expression, by id and by
// tool identifier. The search assertions are the reason it was written: the
// expression was missing from the page payload entirely, so the one thing a
// person holding a hash actually has -- a guess at the construction -- found
// nothing.
//
// This is the only JavaScript in the repository other than the page itself.
// Testing the page's logic needs a JavaScript engine; node is the one that is
// already present. Everything else stays Perl.
//
// USAGE
//   node tools/test-index-page.js docs/index.html
//   Exit 0 all assertions passed, 1 one or more failed, 2 usage.
//
//-----------------------------------------------------------------------
// Generated by Claude Opus 5 on 2026-08-30

const fs = require('fs');

if (process.argv.length < 3) {
  console.error('usage: node tools/test-index-page.js docs/index.html');
  process.exit(2);
}

const src = fs.readFileSync(process.argv[2], 'utf8');
const js = src.match(/<script>([\s\S]*?)<\/script>/)[1];

let lastRows = '';                       // whatever render() last wrote to tb
const mk = (id) => ({
  id, value: '', textContent: '', className: '', dataset: {c: '0'},
  classList: { add(){}, remove(){}, toggle(){} },
  scrollIntoView(){}, set innerHTML(v){ lastRows = v; }, get innerHTML(){ return lastRows; },
});
const els = {};
const document = {
  getElementById(id) {
    if (els[id]) return els[id];
    // A row element exists only if render() emitted an id for it.
    if (lastRows.includes('<tr id="' + id + '"')) return (els[id] = mk(id));
    if (['tb','q','tool','state','cov','gaps','count','note'].includes(id)) return (els[id] = mk(id));
    return null;
  },
  querySelectorAll(){ return { forEach(){} }; },
};
const location = { hash: '' };
const window = { addEventListener(){} };
eval(js);                                 // defines render(), focusHash(), runs both

const checks = [];
checks.push(['rows carry their entry id', /<tr id="[a-z0-9][a-z0-9._-]*">/.test(lastRows)]);
checks.push(['a known entry is present', lastRows.includes('<tr id="rmd320">')]);
checks.push(['permalink anchor emitted', lastRows.includes('href="#rmd320"')]);
// A tombstone id should produce the redirect note and land on the survivor.
location.hash = '#ripemd320';
els.note = mk('note');
focusHash();
checks.push(['tombstone note names the survivor', els.note.textContent.includes('rmd320')]);
checks.push(['tombstone note is shown', els.note.className === 'on']);
location.hash = '#no-such-entry';
focusHash();
checks.push(['unknown id reports itself', els.note.textContent.includes('no-such-entry')]);

// Search: the point of putting the expression and the id in the payload is
// that someone holding a hash and a guess can find the row.
function search(term){ els.q.value = term; render(); return lastRows; }
checks.push(['search finds an expression', search('md5($p.$s)').includes('<tr id=')]);
checks.push(['search finds an id', search('rmd320').includes('<tr id="rmd320">')]);
checks.push(['search finds a hashcat mode', search('4710').includes('<tr id=')]);
checks.push(['nonsense finds nothing', search('zzzznope') === '']);
els.q.value = '';

// THE COVERAGE FACET. Three assertions, and the middle one is the point: a
// filter that returns rows is not evidence it filtered, since returning
// EVERYTHING also returns rows. So the 3-of-3 view must be non-empty, must be
// strictly smaller than the unfiltered table, and must contain no cell
// reporting fewer than three -- which is the only check that can tell "the
// filter works" from "the filter is wired to nothing".
function coverage(v){ els.cov.value = v; render(); const out = lastRows;
                      els.cov.value = ''; render(); return out; }
const all3 = coverage('3');
const countRows = (h) => (h.match(/<tr id=/g) || []).length;
checks.push(['coverage 3 of 3 returns rows', countRows(all3) > 0]);
checks.push(['coverage 3 of 3 is a subset', countRows(all3) < countRows(lastRows)]);
checks.push(['coverage 3 of 3 shows only 3/3', !/>[012]\/3</.test(all3)]);
// The orthogonal one: 'open' asks whether a suite has yet to answer, which is
// independent of how many have proved it. It must not simply repeat a count.
const open = coverage('open');
checks.push(['coverage open returns rows', countRows(open) > 0]);
checks.push(['coverage open is a subset', countRows(open) < countRows(lastRows)]);
checks.push(['coverage open shows no settled row', !/every suite has answered/.test(open)]);

let bad = 0;
for (const [what, ok] of checks) { if (!ok) bad++; console.log((ok ? 'ok   ' : 'FAIL ') + what); }
process.exit(bad ? 1 : 0);
