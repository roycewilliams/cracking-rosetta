#-----------------------------------------------------------------------
#
# Name: merge.pl
# Project: cracking-rosetta
# Phase: curation -- resolving the `duplicate` queue from tools/curate.pl
# Task: merge two entries that name one computation, leaving the loser as a
#       tombstone rather than deleting it.
#
#-----------------------------------------------------------------------
# METHODOLOGY AND WHY THESE CHOICES
#
# WHY THIS EXISTS WHEN tools/dedupe.pl ALREADY MERGES
#
# dedupe.pl predates the 2026-08-30 tombstone decision: it merges and DELETES.
# An id in this repository is a filename stem, a URL fragment in
# docs/index.html and the key in dist/rosetta.csv, and README promises it never
# goes away. Deleting one breaks every consumer that stored it. So a merge here
# empties the loser of every claim and leaves behind a redirect --
# `status: merged`, `merged_into:`, and a mirrored `duplicate-of` edge -- which
# is the shape validate.pl and render.pl already understand.
#
# dedupe.pl also chooses the survivor itself, from mdxfind identity. Which id
# survives is curation: it is the name a reader is most likely to arrive by,
# and no rule in the data decides it. So the survivor is an argument here.
#
# WHY A TIER IS NEVER RAISED BY A MERGE
#
# A tool block carries ONE tier for the whole block, so unioning the loser's
# identifiers into the winner's block silently extends the winner's tier over
# identifiers that were never proven at that strength. Where the loser's tier
# is weaker than the winner's, that is a false claim -- exactly the thing the
# prime directive forbids -- so this script REFUSES the merge and says so,
# rather than resolving it in whichever direction is convenient. Equal tiers
# union freely; a stronger loser tier is absorbed at the winner's weaker tier,
# which loses information but cannot assert anything untrue.
#
# WHY THE WINNER'S BLOCK NOTE IS APPENDED TO
#
# Those notes say how the identifiers in the block were established ("mode
# discovered by round-trip search, not by name"). After a union that sentence
# no longer covers everything in the list, so the merge records which
# identifiers arrived from where. Without it the provenance of half the list is
# lost in the git history of a different file.
#
# WHAT IS DELIBERATELY NOT DONE
#
# Nothing is invented. The loser's expression, category, aliases, legacy names
# and vectors move only into fields the winner does not already fill; where
# both fill a field with different content the script reports and refuses. It
# does not touch `status:`, because "needs-review" is a statement about the
# entry that merging does not answer.
#
# DEPENDENCIES
#
#   YAML::XS       (reading; the repo's emitter is used for writing, because
#                   YAML::XS chooses its own key order -- see RosettaEmit)
#   tools/lib/RosettaEmit.pm
#
# Run tools/validate.pl afterwards: it owns the tombstone rules and this
# script deliberately does not re-implement them.
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-09-01

