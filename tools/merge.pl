# The merge list.

my @jobs;
for my $p (@pairs) {
    my ($l, $w) = split /:/, $p, 2;
    die "--merge wants LOSER:WINNER, got '$p'\n" unless defined $w && length $l && length $w;
    push @jobs, { loser => $l, winner => $w, note => $note };
}
if ($from) {
    open my $fh, '<', $from or die "cannot read $from: $!\n";
    while (my $line = <$fh>) {
        chomp $line;
        next if $line =~ /^\s*(#|$)/;          # comment or blank
        my ($l, $w, $n) = split /\t/, $line, 3;
        die "$from line $.: want loser<TAB>winner\n" unless defined $w;
        push @jobs, { loser => $l, winner => $w, note => ($n // $note) };
    }
    close $fh;
}

for my $j (@jobs) {
    die "no --note for $j->{loser} -> $j->{winner}; a tombstone needs a reason\n"
        unless defined $j->{note} && length $j->{note};
}

