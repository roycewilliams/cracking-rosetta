#-----------------------------------------------------------------------
#
# Name: check-upstream.pl
# Description: execute data/upstream-disagreements.yaml -- fail when a
#              recorded disagreement with a vendored upstream changes state
# Category: cracking-rosetta gate
#
# Project: cracking-rosetta | Phase: upstream drift
#
#-----------------------------------------------------------------------
# METHODOLOGY AND WHY THESE CHOICES
#
# THE PROBLEM: A DISAGREEMENT NOBODY EXECUTES
#
# vendor/ holds upstream's documents byte for byte and is never edited. That
# rule is right: the re-fetch diff is the entire drift signal, and one local
# "fix" inverts it -- a re-fetch would then raise a false alarm every time
# upstream had NOT changed (our edit being reverted) and go silent on the day
# it finally did (the local value already matching). Alarm when nothing
# happened, silence when it did.
#
# So where this repository has disproved a published value, the correction
# lives in data/algorithms/ with its evidence and the two layers hold
# different strings on purpose. Measured 2026-09-02, that was true in two
# places and NOTHING connected them: the relationship was a prose paragraph
# in vendor/cynosureprime/PROVENANCE.md, which no program reads.
#
# THREE FAILURE MODES, AND THE THIRD IS THE POINT
#
#   1. upstream no longer matches what the register recorded -- upstream
#      moved, go look. Today this is only caught if a human reads the
#      re-fetch diff.
#   2. our side no longer matches -- somebody re-seeded upstream's value over
#      a proven one. That is exactly how the bad e607 vector arrived here in
#      the first place, and the prose note was the only guard against it.
#   3. the two have CONVERGED -- upstream fixed it, so the record is spent and
#      should be deleted. A register with no way to shrink becomes a
#      graveyard, and this is the state change nothing could detect at all:
#      today it looks exactly like "nothing happened".
#
# (3) is what turns a re-fetch that changes nothing into a PASSING TEST rather
# than an absence of evidence.
#
# WHY THIS IS NOT PART OF validate.pl
#
# validate.pl answers one question -- is a curated entry well formed, and does
# every identifier it names exist in the committed inventories. It reads
# data/algorithms and data/tools and deliberately nothing else. This reads
# vendor/, which is a different layer with a different rule attached to it
# (never edit), and it is the natural thing to run straight after
# tools/fetch-upstream.sh. Two gates, two questions.
#
# WHY THE KINDS ARE HARD-CODED
#
# A register that needs a plugin architecture has stopped being a list of
# specific evidenced disagreements. There are two kinds, each with a fixed
# pair of accessors written out below, and adding a third should feel
# expensive enough that somebody asks whether the disagreement is real first.
#
# WHAT DID NOT GENERALISE, RECORDED RATHER THAN PAPERED OVER
#
# The register was sketched as (upstream publishes X, we assert Y) and the
# second seed record does not fit that shape: a catalog that lags a binary is
# a SET DIFFERENCE, not one string against another, and forcing it into
# publishes:/we_assert: would have meant writing a thousand indices into a
# field. What did generalise is the core -- id, kind, upstream, inventory,
# because, recorded -- and the three failure modes, which both kinds have.
#
# THE SECOND RECORD ALSO ABSORBS A FICTIONAL TOOL
#
# CLAUDE.md records hashpipe as an ALIAS of mdxfind rather than a fourth
# column "until that stops being true", and says tools/extract-hashpipe.pl
# exists to detect the divergence. Verified 2026-09-02: it does not exist, so
# the documented detector was a human remembering to read a diff. The
# catalog-index-set check is that detector -- on every shared index the
# catalog and the binary must agree on the name and on the hashcat mapping.
#
# ONE ORDERING RULE THAT MATTERS
#
# When upstream fixes a value, mode 1 and mode 3 are BOTH true: upstream no
# longer matches what we recorded, and the two sides now agree. Convergence is
# reported alone, because "delete this record" is the whole action and
# "upstream moved" underneath it would send a reader looking for a second
# problem that is not there.
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-09-02

