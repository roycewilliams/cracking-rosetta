#!/usr/bin/perl
#
# coverage-report.pl -- how much of the corpus actually cross-references
#
# PURPOSE
#
# validate.pl reports per-tool coverage: what fraction of hashcat's modes,
# mdxfind's types and john's formats have an entry. Those numbers went from
# 48/73/38 percent to 90/95/73 in one session and they are real -- but on
# their own they measure the wrong axis, and reading them alone will make a
# session think the job is closer to done than it is.
#
# A row that names ONE tool proves that tool does the thing. It does not tell
# anyone what to call it anywhere else, which is what somebody came here for.
# The project is a rosetta stone: the product is the JOIN. So the number that
# matters is how many entries name two tools or three, and this prints it.
#
# Measured 2026-08-31, right after the seeding passes: 149 entries at three
# columns, 331 at two, 916 at one -- 65.5% of the corpus single-column. That
# is the number to move, and moving it is what discover-hashcat.pl and
# discover-mdxfind.pl are for (see STATE.md, START HERE).
#
# Tombstones are excluded: a merged-away id is a redirect, not an algorithm.
# Crack is not counted as a column -- it is historical reference only and
# implements nothing itself, so it can never be the thing a reader is
# translating to.
#
# Usage: coverage-report.pl [--algorithms DIR] [--list-single] [-v]
#
# Generated by Claude Opus 5 on 2026-08-31

use strict;
use warnings;
use FindBin qw($RealBin);
use lib "$RealBin/lib";
use Getopt::Long qw(GetOptions);
use File::Basename qw(basename);
use YAML::XS qw(LoadFile);

my $PROG = basename($0);
my $ROOT = "$RealBin/..";
my $algdir = "$ROOT/data/algorithms";
my ($list_single, $verbose, $help) = (0,0,0);

sub usage {
    print STDERR <<"USAGE";

Usage: $PROG [options]

   --algorithms DIR  curated entries (default: data/algorithms)
   --list-single     print every single-column entry and which tool it names
   -v, --verbose     also break the single-column count down by tool
   -h, --help        this help

   Prints how many entries name three tools, two, one or none. The
   single-column count is the number that says how far this is from being a
   cross-reference rather than three indexes in a trench coat.

   Exit 0 success, 2 usage.

USAGE
    exit 2;
}

GetOptions(
    'algorithms=s' => \$algdir,
    'list-single'  => \$list_single,
    'verbose|v+'   => \$verbose,
    'help|h'       => \$help,
) or usage();
usage() if $help;

# tools_named($entry) - which of the three real columns this entry populates.
sub tools_named {
    my ($e) = @_;
    my @t;
    my $hc = $e->{tools}{hashcat}{modes};
    push @t, 'hashcat' if ref $hc eq 'ARRAY' && @$hc;
    my $mx = $e->{tools}{mdxfind}{types};
    push @t, 'mdxfind' if ref $mx eq 'ARRAY' && @$mx;
    my $jc = $e->{tools}{john}{cpu};
    my $jg = $e->{tools}{john}{gpu};
    push @t, 'john' if (ref $jc eq 'ARRAY' && @$jc) || (ref $jg eq 'ARRAY' && @$jg);
    return @t;
}

opendir my $dh, $algdir or die "$PROG: $algdir: $!\n";
my @files = sort grep { /\.yaml$/ } readdir $dh;
closedir $dh;

my (%bucket, %only, @singles, @nones, $total, $tomb);
for my $f (@files) {
    my $e = eval { LoadFile("$algdir/$f") } or next;
    next unless $e->{id};
    if (($e->{status} // '') eq 'merged') { $tomb++; next }
    $total++;
    my @t = tools_named($e);
    $bucket{ scalar @t }++;
    if (@t == 1) { $only{ $t[0] }++; push @singles, [ $e->{id}, $t[0], $e->{name} // '' ] }
    push @nones, [ $e->{id}, $e->{name} // '' ] unless @t;
}

printf "- %d entry/entries (%d tombstone(s) excluded)\n", $total, ($tomb // 0);
printf "- Columns:  3 tools %4d   2 tools %4d   1 tool %4d   none %d\n",
    $bucket{3}//0, $bucket{2}//0, $bucket{1}//0, $bucket{0}//0;
printf "- JOINED:   %d of %d (%.1f%%) name more than one tool\n",
    ($bucket{3}//0) + ($bucket{2}//0), $total,
    $total ? 100 * (($bucket{3}//0) + ($bucket{2}//0)) / $total : 0;
printf "- SINGLE:   %d of %d (%.1f%%) name exactly one -- the number to move\n",
    $bucket{1}//0, $total, $total ? 100 * ($bucket{1}//0) / $total : 0;

if ($verbose) {
    printf "-   single-column by tool: %s\n",
        join('  ', map { "$_ $only{$_}" } sort { $only{$b} <=> $only{$a} } keys %only);
}
if (@nones) {
    printf "- NO TOOL AT ALL: %d -- %s\n", scalar @nones,
        join(', ', map { $_->[0] } @nones);
}
if ($list_single) {
    printf "%-46s %-8s %s\n", @$_ for sort { $a->[1] cmp $b->[1] || $a->[0] cmp $b->[0] } @singles;
}
exit 0;
