# --oracle: is the FIXTURE still what upstream says? Everything above only
# proves RosettaExpr agrees with a table of strings; this proves the table
# still agrees with mdxfind. Separate on purpose, because CI has no hx.
#-----------------------------------------------------------------------
if ($oracle) {
    my $hx = $ENV{HX} || "$RealBin/../tmp/hx-build/hx";
    unless (-x $hx) {
        print STDERR "- oracle: no hx binary at $hx (build it, or set HX=)\n";
        $fail_n++;
    }
    else {
        my $checked = 0;
        for my $c (@CASES) {
            my ($hxe, undef, $want, $why, $pw) = @$c;
            $pw = $PASS unless defined $pw;
            next unless defined $hxe && defined $want;
            # -p/-s are passed as separate argv entries, so nothing is
            # interpolated by a shell.
            my $pid = open(my $fh, '-|');
            defined $pid or die "fork: $!";
            unless ($pid) {
                open(STDERR, '>', '/dev/null');
                exec($hx, '-p', $pw, '-s', $SALT, $hxe) or exit 127;
            }
            my $got = do { local $/; <$fh> };
            close $fh;
            $got = '' unless defined $got;
            $got =~ s/\n\z//;
            $checked++;
            check($got eq $want, "oracle: $why",
                  "     $hxe\n     fixture $want\n     hx      $got\n");
        }
        printf STDERR "- oracle: %d case(s) re-measured against %s\n",
            $checked, $hx;
    }
}

printf STDERR "- %d passed, %d failed\n", $pass_n, $fail_n;
exit($fail_n ? 1 : 0);
