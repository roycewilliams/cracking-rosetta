# METHODOLOGY AND WHY THIS EXISTS
#
# RosettaExpr is an INDEPENDENT implementation of what an entry's expression
# computes. triage-expressions.pl uses it as the control that separates "john
# will not reproduce this" from "nobody can", and on the strength of a
# `corroborated` or `expression-wrong` verdict curate.pl either files a human
# question or suppresses one. So an off-by-one in cut(), or a cap() that
# capitalises the first CHARACTER rather than the first lower-case LETTER,
# does not fail loudly: it reports a correct expression as wrong, and buries
# or invents a curation question. That is the same trap that kept the module
# deliberately tiny in the first place.
#
# THE EXPECTED VALUES ARE UPSTREAM'S, NOT MINE
#
# Every value below was MEASURED by running mdxfind's own standalone hx
# evaluator, built from the source tree named in CLAUDE.md as the highest
# authority there is:
#
#   cc -O2 -I$M -DHX_STANDALONE -o hx $M/hx.c $M/hx_func.c $M/hx_ast.c \
#      $M/hx_compile.c $M/hx_vm.c $M/hx.tab.c $M/hx.lex.c $M/crypt-des.c \
#      $M/myprogress.c -lcrypto -lssl
#   ./hx -p rosetta -s NaCl 'base64(sha1_bin(salt . pass))'
#
# measured 2026-09-02 against mdxfind source RCS 1.545. That is why cases are
# carried in BOTH spellings: `hx` is the string that was handed to the oracle,
# `expr` is the same construction in this repository's notation ($p, $s,
# _raw). --oracle re-runs the whole table through a live hx binary and checks
# the fixture itself has not drifted, which is what makes re-measuring after
# an upstream pull a command rather than a memory.
#
# WHY THE REFUSALS MATTER MORE THAN THE AGREEMENTS
#
# A construction RosettaExpr cannot compute must return undef, never a value
# computed from a silently dropped token. Every refusal below is a function
# this host genuinely cannot evaluate (md4 -- no Digest::MD4 here; whirlpool,
# gost, ripemd, haval, sha3 likewise) or a shape outside the grammar. If one
# of them starts returning a value, triage gains a verdict it has not earned.
#
# NOT being in hx is NOT a reason to refuse, and saying so cost this fixture
# two wrong assertions until 2026-09-04. `sha224` and `sha384` are absent
# from hx's function table but present in this corpus's expression: fields,
# which take them from john's dynamics; they are computed exactly by core
# Perl, and the entries carrying them hold john-proven vectors that pin what
# the token means. The right question for a refusal is whether this host can
# compute the construction, not which upstream happens to spell it.
#
# USAGE
#   perl tools/test-rosetta-expr.pl            fixture only, no hx needed
#   perl tools/test-rosetta-expr.pl --oracle   also re-measure against hx
#   HX=/path/to/hx  overrides where the oracle is looked for.
#   Exit 0 all assertions passed, 1 one or more failed, 2 usage.
#
# DEPENDENCIES
#   perl, tools/lib/RosettaExpr.pm; --oracle additionally needs a built hx
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-09-02

