#-----------------------------------------------------------------------
# hashpipe's registration table.
#
# Six macros register a type and the example is the LAST argument of every
# one of them:
#
#   HT(name, len, flags, fn, ex)        HTC(name, len, flags, chain, ex)
#   HT_ALT(name, len, flags, fn, alt, ex)   HTV(name, flags, vfn, ex)
#   HT_ALT2(name, len, flags, fn, alt, alt2, ex)  HTVC(name, flags, vfn, vc, ex)
#
# so the call is scanned to its closing paren, with strings stepped over, and
# the last string literal in the argument list is the example. A call with no
# string after the name is a type with no vector, which is what PARALLEL is
# and why `hashpipe -T` skips it.

# skip_to_close($txt, $i) - $i is just past the opening paren; return the index
# of its match, with strings and both comment styles stepped over.
sub skip_to_close {
    my ($txt, $i) = @_;
    my $len   = length $txt;
    my $depth = 1;
    while ($i < $len) {
        my $ch  = substr($txt, $i, 1);
        my $two = substr($txt, $i, 2);
        if ($two eq '/*') { my $e = index($txt, '*/', $i + 2); $i = $e < 0 ? $len : $e + 2; next }
        if ($two eq '//') { my $e = index($txt, "\n", $i);     $i = $e < 0 ? $len : $e + 1; next }
        if ($ch eq '"' || $ch eq "'") {
            my $q = $ch; $i++;
            while ($i < $len) {
                my $c = substr($txt, $i, 1);
                last if $c eq $q;
                $i += ($c eq "\\") ? 2 : 1;
            }
            $i++;
            next;
        }
        $depth++ if $ch eq '(';
        if ($ch eq ')') { $depth--; return $i if $depth == 0 }
        $i++;
    }
    return -1;
}

# c_unescape($body) - the bytes a C string literal denotes, given its INSIDE.
sub c_unescape {
    my ($s) = @_;
    my ($out, $i, $len) = ('', 0, length $s);
    while ($i < $len) {
        my $ch = substr($s, $i, 1);
        if ($ch ne "\\") { $out .= $ch; $i++; next }
        my $esc = substr($s, $i + 1, 1);
        $i += 2;
        if    ($esc eq 'n') { $out .= "\n" }
        elsif ($esc eq 't') { $out .= "\t" }
        elsif ($esc eq 'r') { $out .= "\r" }
        elsif ($esc eq 'x') {
            my $h = '';
            $h .= substr($s, $i++, 1)
                while $i < $len && substr($s, $i, 1) =~ /[0-9a-fA-F]/ && length($h) < 2;
            return undef unless length $h;
            $out .= chr(hex $h);
        }
        elsif ($esc =~ /[0-7]/) {
            my $o = $esc;
            $o .= substr($s, $i++, 1)
                while $i < $len && substr($s, $i, 1) =~ /[0-7]/ && length($o) < 3;
            $out .= chr(oct $o);
        }
        else { $out .= $esc }
    }
    return $out;
}

my %EXAMPLE;
sub load_examples {
    open my $fh, '<:raw', $src or do {
        print STDERR "$PROG: cannot read hashpipe source $src: $!\n"; exit 1;
    };
    my $txt = do { local $/; <$fh> };          # $/ is the input record separator
    close $fh;
    my $n = 0;
    while ($txt =~ /\bHT(?:_ALT2?|C|V|VC)?\s*\(\s*"((?:[^"\\]|\\.)*)"\s*,/g) {
        my $name  = c_unescape($1);
        my $start = pos $txt;
        my $close = skip_to_close($txt, $start);
        next if $close < 0;
        my $args  = substr($txt, $start, $close - $start);
        my @lit   = $args =~ /"((?:[^"\\]|\\.)*)"/g;
        next unless @lit;
        my $ex = c_unescape($lit[-1]);
        next unless defined $ex && length $ex;
        # Uppercase for the lookup: john and the sheet are both inconsistent
        # about case, so the corpus is not guaranteed to spell a type as the
        # tool does. The tool's own spelling is what gets pinned.
        $EXAMPLE{ uc $name } = { name => $name, example => $ex };
        $n++;
    }
    return $n;
}

