# Targets.

my $nex = load_examples();
printf STDERR "%s: %d hashpipe type(s) with an example in %s\n", $PROG, $nex, $src
    if $verbose;

my $mx_inv = eval { YAML::XS::LoadFile("$ROOT/data/tools/mdxfind.yaml") };
my %MX_SALTED;
if ($mx_inv) {
    for my $t (@{ $mx_inv->{types} }) {
        $MX_SALTED{ uc $t->{name} } = 1
            if grep { $_ eq 's' || $_ eq 'u' } @{ $t->{flags} || [] };
    }
}
else {
    print STDERR "$PROG: cannot load the mdxfind inventory; assuming no type is salted.\n";
}

opendir(my $dh, $algdir) or do { print STDERR "$PROG: cannot read $algdir: $!\n"; exit 1 };
my @files = sort grep { /\.yaml$/ } readdir $dh;
closedir $dh;

my (@cand, @noscore);
my $targets = 0;

for my $f (@files) {
    my $path = "$algdir/$f";
    my $e = eval { YAML::XS::LoadFile($path) };
    unless ($e) { print STDERR "$PROG: cannot load $path: $@\n"; exit 1 }
    my $id = $e->{id} // ($f =~ s/\.yaml$//r);
    next if %only && !$only{$id};
    next if ($e->{status} // '') eq 'merged';
    next if $e->{vectors} && @{ $e->{vectors} };
    my @types = @{ $e->{tools}{mdxfind}{types} || [] };
    next unless @types;
    $targets++;

    my $hit;
    for my $t (@types) {
        my $x = $EXAMPLE{ uc $t } or next;
        # hashpipe's own self-test splits the example with strrchr(ex, ':').
        my $i = rindex($x->{example}, ':');
        next if $i <= 0;
        my ($hash, $pass) = (substr($x->{example}, 0, $i),
                             substr($x->{example}, $i + 1));
        next unless length $hash && length $pass;
        next if "$hash$pass" =~ /[\r\n]/;
        $hit = {
            id   => $id, path => $path, entry => $e,
            type => $x->{name},
            iter => ($e->{tools}{mdxfind}{iterations} // 1),
            salted => ($MX_SALTED{ uc $t } ? 1 : 0),
            hash => $hash, pass => $pass,
        };
        last;
    }
    if ($hit) { push @cand, $hit }
    else      { push @noscore, $id }
}

#-----------------------------------------------------------------------
# Run.

my $started = time;
my (@ok, @bad);
my $n = 0;

printf "# %s -- %d entr%s with no vector naming an mdxfind type; %d with a hashpipe example, %d without\n",
    $PROG, $targets, ($targets == 1 ? 'y' : 'ies'), scalar @cand, scalar @noscore;
print "# columns: result, entry, type, hashpipe, mdxfind, hash, pass\n";

for my $c (@cand) {
    last if $limit && $n >= $limit;
    $n++;

    if ($dry) {
        printf "PLAN\t%s\t%s\t-\t-\t%s\t%s\n", $c->{id}, $c->{type}, $c->{hash}, $c->{pass};
        next;
    }

    my ($good, $why) = hashpipe_verifies($c->{type}, $c->{hash}, $c->{pass}, $c->{iter});
    my $mx = ($no_mdxfind || !$good) ? '-'
           : mdxfind_reads($c->{type}, $c->{hash}, $c->{pass}, $c->{iter}, $c->{salted});
    $c->{mdxfind} = $mx;

    printf STDERR "-   %-24s %-22s hashpipe %-10s mdxfind %s\n",
        $c->{id}, $c->{type}, ($good ? 'verified' : "FAILED"), $mx if $verbose;

    if ($good) {
        push @ok, $c;
        printf "OK\t%s\t%s\tverified\t%s\t%s\t%s\n",
            $c->{id}, $c->{type}, $mx, $c->{hash}, $c->{pass};
    }
    else {
        push @bad, [$c, $why];
        printf "FAIL\t%s\t%s\t%s\t-\t%s\t%s\n",
            $c->{id}, $c->{type}, $why, $c->{hash}, $c->{pass};
    }
}

print "SKIP\t$_\t-\tno hashpipe example\t-\t-\t-\n" for @noscore;

#-----------------------------------------------------------------------
# Write.

my $written = 0;
if ($apply) {
    my %touched;
    for my $c (@ok) {
        push @{ $c->{entry}{vectors} }, {
            hash   => $c->{hash},
            pass   => $c->{pass},
            source => 'hashpipe',
        };
        $touched{ $c->{path} } = $c->{entry};
    }
    $written += emit_entry($_, $touched{$_}) for sort keys %touched;
}

my $elapsed = time - $started;
printf STDERR "%s: %d candidate(s) examined, %d verified by hashpipe, %d failed, %d file(s) written in %.1fs\n",
    $PROG, $n, scalar @ok, scalar @bad, $written, $elapsed;

if (@ok && !$no_mdxfind) {
    my $yes = grep { $_->{mdxfind} =~ /^yes/ } @ok;
    printf STDERR "%s: mdxfind reads %d of the %d, pinned to the same type. The rest are a MEASURED gap between the two tools, not an untested one.\n",
        $PROG, $yes, scalar @ok;
}
if ($apply && $written) {
    printf STDERR "%s: tiers untouched. Promote what is now provable with:\n    ./tools/verify-vectors.pl --tool mdxfind -v\n", $PROG;
}

exit 0;
