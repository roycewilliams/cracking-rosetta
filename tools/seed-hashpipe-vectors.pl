#!/usr/bin/perl
#
# seed-hashpipe-vectors.pl -- give an entry that has no test vector the one
# hashpipe ships for the mdxfind type it names, and prove it by re-verifying it.
#
# WHY THIS EXISTS
#
# This is the third and last route into the entries that carry no vector at
# all. seed-vectors.pl reads the published example out of data/tools/*.yaml
# and seed-john-vectors.pl reads john's own source; between them they leave a
# residue that names an mdxfind type and NO john format, so john's source has
# nothing to offer it, and whose mdxfind inventory row has no example_vector
# either. hashpipe has one for all but a single registered type: `ht->example`
# is the last argument of every HT/HT_ALT/HT_ALT2/HTC/HTV/HTVC registration in
# hashpipe.c, and `hashpipe -T` reproduces all 1026 of them.
#
# WHY THE SOURCE AND NOT THE CATALOG
#
# CLAUDE.md's authority order: the source, then the binary's own output, then
# the specification, then HASH_TYPES.md. The vendored catalog is the weakest
# of the four and here it is also the stalest -- it publishes 1000 types as of
# v1.102 where the binary is v1.192 with 1026, so several of these types are
# not in it at all. `hashpipe -G` looked like the binary-output answer and is
# not: it GENERATES a vector for a type that has no ht->example and prints
# nothing for the ones that do (hashpipe.c, the `if (!ht->example)` branch).
#
# WHY THE SPLIT ON THE LAST COLON IS NOT A GUESS
#
# An example is "hash[:salt]:password" and a salt can contain a colon --
# SHA1MD5HUM's is "00- x 1". hashpipe's own self-test splits it with
# strrchr(ex, ':'), so this does the same. It is the tool's parse of the tool's
# own field, not a rule invented here.
#
# WHAT VERIFIES IT
#
# `hashpipe -c`, which verifies each line against its own leading TYPE label
# and runs no detection -- the per-line equivalent of `mdxfind -h '^TYPE$'`.
# One line per invocation, streams kept apart, and the EMITTED label compared
# with the one asked for: those three are the reading traps CLAUDE.md records,
# and the second is the one that makes a refusal look exactly like a pass.
# That -c is actually strict is not assumed here; tools/test-hashpipe-c.pl
# asserts it in 37 measurements, including every off-diagonal cell of
# md5^1..md5^5 and the batch path that leaked twice.
#
# WHY IT ALSO RUNS MDXFIND, AND WHY THAT DOES NOT GATE
#
# hashpipe is not a column in this repository; what a vector like this stands
# to promote is the MDXFIND block. So mdxfind is asked, pinned to the same
# type, and its answer is REPORTED -- but it does not gate the write, because
# a serialization mdxfind cannot read is still a true hash/plaintext pair for
# the algorithm and is exactly what makes the mdxfind gap a measured fact
# rather than an untested one. verify-vectors.pl owns tiers and has a solo
# fallback for the types whose report line does not echo what it was given.
#
# DEPENDENCIES: YAML::XS, tools/lib/RosettaEmit.pm, a hashpipe binary, a
# readable hashpipe.c, and optionally mdxfind. Run from anywhere.
#
# Generated by Claude Opus 5 on 2026-09-04

