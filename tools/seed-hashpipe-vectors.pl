sub write_file {
    my ($path, @lines) = @_;
    open my $fh, '>', $path or die "$PROG: cannot write $path: $!\n";
    print {$fh} "$_\n" for @lines;
    close $fh;
    return $path;
}

# run_capture($secs, @argv) - (exit, stdout). stderr is DELIBERATELY not
# merged: `hashpipe -c` echoes a REFUSED line to stderr verbatim, so a merged
# stream is consistent with both a pass and a refusal and cannot tell you which.
sub run_capture {
    my ($secs, @argv) = @_;
    my $out = '';
    my $pid = open(my $fh, '-|');
    defined $pid or return (-1, '');
    if (!$pid) {
        open STDERR, '>', '/dev/null';
        exec { $argv[0] } @argv or exit 127;
    }
    my $killed = 0;
    eval {
        local $SIG{ALRM} = sub { $killed = 1; kill 'KILL', $pid; die "timeout\n" };
        alarm $secs;
        local $/;
        $out = <$fh> // '';
        alarm 0;
    };
    alarm 0;
    close $fh;
    return ($killed ? -2 : ($? >> 8), $out);
}

# hashpipe_verifies($type, $hash, $pass, $iter) - one line, pinned to its own
# label, stdout only. Returns (ok, reason).
sub hashpipe_verifies {
    my ($type, $hash, $pass, $iter) = @_;
    (my $safe = $type) =~ s/[^A-Za-z0-9._-]/_/g;
    # Ask BARE and let the tool say what depth matched: the emitted label is
    # bare where the input was bare or x01, mdxfind's own convention.
    my $in = write_file("$workdir/hp.$safe.in", "$type $hash:$pass");
    my ($code, $out) = run_capture($timeout, '/bin/sh', '-c',
        sprintf('%s -c < %s 2>/dev/null', quotemeta($hashpipe), quotemeta($in)));
    return (0, 'timeout') if $code == -2;
    for my $line (split /\n/, $out) {
        next unless $line =~ /^\Q$type\E(?:x(\d+))?\s+(.+)$/;
        # The suffix is part of the identity. A bare emission is the FIRST
        # iteration stated by the tool, so it reads as 1 and not as "unknown".
        my $got = defined $1 ? $1 + 0 : 1;
        return (0, "verified at x$got, entry declares x$iter") unless $got == $iter;
        return (1, '') if $2 eq "$hash:$pass";
        return (0, 'reproduced a different string');
    }
    return (0, 'refused');
}

# mdxfind_reads($type, $hash, $pass, $iter, $salted) - informational only.
sub mdxfind_reads {
    my ($type, $hash, $pass, $iter, $salted) = @_;
    (my $safe = $type) =~ s/[^A-Za-z0-9._-]/_/g;
    my $hf = write_file("$workdir/mx.$safe.hash", $hash);
    my $wf = write_file("$workdir/mx.$safe.word", $pass);
    my ($code, $out) = run_capture($timeout, $mdxfind,
        '-h', "^\Q$type\E\$", ($salted ? '-F' : '-f'), $hf, '-i', $iter, $wf);
    return 'timeout' if $code == -2;
    for my $line (split /\n/, $out) {
        next unless $line =~ /^\Q$type\E(?:x(\d+))?\s+(.+)$/;
        my $got = defined $1 ? $1 + 0 : $iter;
        next unless $got == $iter;
        # An exact echo is the strong answer. mdxfind does not always echo what
        # it was given -- a type whose salt rides INSIDE the hash field prints
        # "(null)" in the salt slot -- so a line that names the pinned type and
        # ends in this plaintext, with one hash in the file, is reported as a
        # weaker "yes (re-serialized)" rather than silently as either.
        return 'yes' if $2 eq "$hash:$pass";
        return 'yes (re-serialized)' if $2 =~ /(?:^|:)\Q$pass\E$/;
    }
    return 'no';
}

