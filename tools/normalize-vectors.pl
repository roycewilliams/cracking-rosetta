    'john=s' => \$john, 'mdxfind=s' => \$mdxfind, 'hashcat=s' => \$hashcat,
    'drop-junk' => \$drop, 'apply' => \$apply,
    'v|verbose+' => \$verbose, 'h|help' => \$help,
) or do { usage(); exit 2 };
if ($help) { usage(); exit 0 }
if (!@only && !$apply && !$verbose && !$drop) { usage(); exit 2 }

$algdir  //= "$ROOT/data/algorithms";
$workdir //= "$ROOT/tmp/normalize";
$john    = tool_path('john',    $john);
$mdxfind = tool_path('mdxfind', $mdxfind);
$hashcat = tool_path('hashcat', $hashcat);
mkdir $workdir unless -d $workdir;
my %scope = map { $_ => 1 } @only;

my ($jdir, $jbin) = $john =~ m{^(.*)/([^/]+)$} ? ($1, $2) : ('.', $john);

#-----------------------------------------------------------------------
# Shape tests.
#
# looks_tagged: john's own ciphertext for a dynamic format. The tag is what
# makes it unreadable elsewhere; everything after it is ours to reshape.
sub looks_tagged { return $_[0] =~ /^\$dynamic_\d+\$/ }

# looks_like_junk: not a hash by any encoding this repository uses.
#
# Deliberately narrow, and narrowed once already after a false positive worth
# remembering: netntlmv1's vector is "::WG:aaaa...:3a29...:1122334455667788",
# whose FIRST colon-separated field is empty. Judging fields made a perfectly
# good challenge-response ciphertext look like junk, and --drop-junk would
# have deleted it. So the test is on the whole string: junk is short AND
# carries no hash characters at all, which is true of "--" and of nothing
# legitimate here.
sub looks_like_junk {
    my ($h) = @_;
    return 0 if $h =~ /^\$/;                 # tagged ciphertext: fine
    return 0 if length($h) >= 8;
    return 1 if $h !~ /[0-9a-zA-Z]/;         # '--', '...', ''
    return 0;
}

#-----------------------------------------------------------------------
# Verification, pinned to an identifier the entry already names.

sub run_quiet {
    my ($cmd) = @_;
    return system("$cmd >/dev/null 2>&1") == 0;
}

# verify_with_john($label, $hash, $pass) - does john, as that format, recover
# that plaintext from that vector? The vector is offered both bare and in
# john's tagged form, because which one a dynamic accepts depends on the
# format, and either answer proves the same thing.
sub verify_with_john {
    my ($label, $hash, $pass) = @_;
    (my $safe = "$label-$hash") =~ s/[^A-Za-z0-9]/_/g;
    $safe = substr($safe, 0, 60);
    my ($h, $salt) = split /:/, $hash, 2;
    my @lines = ("v0\t$hash");
    push @lines, "v0\t\$$label\$$h\$$salt"
        if $label =~ /^dynamic_\d+$/ && defined $salt && length $salt;
    push @lines, "v0\t\$$label\$$h"
        if $label =~ /^dynamic_\d+$/ && !(defined $salt && length $salt);

    open my $fh, '>', "$workdir/$safe.hash" or return 0;
    print {$fh} join("\n", @lines), "\n"; close $fh;
    open my $wf, '>', "$workdir/$safe.word" or return 0;
    print {$wf} "$pass\n"; close $wf;
    unlink "$workdir/$safe.pot";

    run_quiet(sprintf('cd %s && ./%s --format=%s --field-separator-char=tab '
                    . '--wordlist=%s --pot=%s --session=%s %s',
        quotemeta($jdir), quotemeta($jbin), quotemeta($label),
        quotemeta("$workdir/$safe.word"), quotemeta("$workdir/$safe.pot"),
        quotemeta("$workdir/$safe"), quotemeta("$workdir/$safe.hash")));
    my $shown = `cd \Q$jdir\E && ./\Q$jbin\E --show --format=\Q$label\E --field-separator-char=tab --pot=\Q$workdir/$safe.pot\E \Q$workdir/$safe.hash\E 2>/dev/null`;
    return $shown =~ /^v0\t\Q$pass\E$/m ? 1 : 0;
}

# verify_with_mdxfind($type, $iters, $hash, $pass) - pinned to one type, which
# is the only way to read an mdxfind result (gotcha: it reports the FIRST
# internal type that reproduces a digest).
sub verify_with_mdxfind {
    my ($type, $iters, $hash, $pass) = @_;
    (my $safe = "$type-$hash") =~ s/[^A-Za-z0-9]/_/g;
    $safe = substr($safe, 0, 60);
    open my $fh, '>', "$workdir/$safe.hash" or return 0;
    print {$fh} "$hash\n"; close $fh;
    open my $wf, '>', "$workdir/$safe.word" or return 0;
    print {$wf} "$pass\n"; close $wf;
    # -F for a vector carrying its salt inline, -f otherwise.
    my $flag = $hash =~ /:/ ? '-F' : '-f';
    my $out = `\Q$mdxfind\E -h '^\Q$type\E\$' $flag \Q$workdir/$safe.hash\E -i \Q$iters\E \Q$workdir/$safe.word\E 2>/dev/null`;
    return $out =~ /\Q$pass\E\s*$/m ? 1 : 0;
}

# verify_with_hashcat($mode, $hash, $pass)
sub verify_with_hashcat {
    my ($mode, $hash, $pass) = @_;
    (my $safe = "hc$mode-$hash") =~ s/[^A-Za-z0-9]/_/g;
    $safe = substr($safe, 0, 60);
    open my $fh, '>', "$workdir/$safe.hash" or return 0;
    print {$fh} "$hash\n"; close $fh;
    open my $wf, '>', "$workdir/$safe.word" or return 0;
    print {$wf} "$pass\n"; close $wf;
    my $out = `\Q$hashcat\E -m \Q$mode\E -a 0 --quiet --potfile-disable --self-test-disable \Q$workdir/$safe.hash\E \Q$workdir/$safe.word\E 2>/dev/null`;
    return $out =~ /\Q$pass\E\s*$/m ? 1 : 0;
}

# verified_by($entry, $hash, $pass) - the first identifier the entry already
# holds at tier vector that reproduces this candidate, or undef.
sub verified_by {
    my ($e, $hash, $pass) = @_;

    my $mx = $e->{tools}{mdxfind};
    if (ref $mx eq 'HASH' && ($mx->{verified} // '') eq 'vector') {
        my $it = $mx->{iterations} || 1;
        for my $t (@{ $mx->{types} || [] }) {
            return "mdxfind $t" if verify_with_mdxfind($t, $it, $hash, $pass);
        }
    }
    my $hc = $e->{tools}{hashcat};
    if (ref $hc eq 'HASH' && ($hc->{verified} // '') eq 'vector') {
        for my $m (@{ $hc->{modes} || [] }) {
            return "hashcat $m" if verify_with_hashcat($m, $hash, $pass);
        }
    }
    my $jn = $e->{tools}{john};
    if (ref $jn eq 'HASH' && ($jn->{verified} // '') eq 'vector') {
        for my $l (@{ $jn->{cpu} || [] }) {
            return "john $l" if verify_with_john($l, $hash, $pass);
        }
    }
    return undef;
}

