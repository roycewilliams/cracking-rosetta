        ($drop ? '' : ' (use --drop-junk to remove)');
    printf STDERR "    %s\n", $_ for @junk_list;
}
if (@fail_list) {
    printf STDERR "- %d tagged vector(s) that NO identifier this entry names could verify;\n"
                . "  left alone. Each is a question about the entry:\n", scalar @fail_list;
    printf STDERR "    %s\n", $_ for @fail_list;
}
printf STDERR "- %d entr(ies) with vectors examined in %ds\n", $seen, time - $start;
printf STDERR "-   tagged %d, rewritten %d, unverifiable %d, junk %d, dropped %d\n",
    $tagged, $rewrote, $failed, $junk, $dropped;
print  STDERR "- nothing written; re-run with --apply\n"
    if !$apply && ($rewrote || $dropped);
print  STDERR "- now run: tools/derive-expressions.pl, tools/verify-vectors.pl, tools/validate.pl\n"
    if $apply && ($rewrote || $dropped);
exit 0;
