my $PROG = basename($0);
my $ROOT = "$RealBin/..";
my $TODAY = do { my @t = localtime; sprintf '%04d-%02d-%02d',
                 $t[5]+1900, $t[4]+1, $t[3] };

sub usage {
    print STDERR <<"END_USAGE";

Usage: $PROG [options]

   --algorithms DIR  curated entries (default: data/algorithms)
   --only ID         just this entry (repeatable)
   --work DIR        scratch for hash/word/pot files (default: tmp/normalize)
   --john PATH       john binary    (default: @{[tool_env_help('john')]})
   --mdxfind PATH    mdxfind binary (default: @{[tool_env_help('mdxfind')]})
   --hashcat PATH    hashcat binary (default: @{[tool_env_help('hashcat')]})
   --drop-junk       also remove vectors whose hash cannot be a hash
   --apply           write; without it nothing is changed
   -v, --verbose     per-vector detail
   -h, --help        this help

   Rewrites a vector carrying john's \$dynamic_N\$ ciphertext tag into this
   repository's shape (digest, or digest:salt), but only when a tool the entry
   already names verifies the rewritten form. Reports vectors that are not
   hashes at all; --drop-junk removes them, never leaving an entry empty.

   Tiers are never changed. Exit 0 success, 1 error, 2 usage.

END_USAGE
