# Walk.

opendir(my $dh, $algdir) or do {
    print STDERR "$PROG: cannot read $algdir: $!\n"; exit 1;
};
my @files = sort grep { /\.yaml$/ } readdir $dh;
closedir $dh;

my $start = time;
my ($seen, $tagged, $rewrote, $failed, $junk, $dropped) = (0) x 6;
my (@junk_list, @fail_list);

for my $file (@files) {
    my $stem = $file; $stem =~ s/\.yaml$//;
    next if %scope && !$scope{$stem};
    my $path = "$algdir/$file";
    my $d = eval { YAML::XS::LoadFile($path) } or next;
    next unless ref $d eq 'HASH';
    next if ($d->{status} // '') eq 'merged';
    next unless ref $d->{vectors} eq 'ARRAY' && @{ $d->{vectors} };
    $seen++;

    my $changed = 0;
    my @keep;
    for my $v (@{ $d->{vectors} }) {
        my $hash = $v->{hash} // '';

        if (looks_like_junk($hash)) {
            $junk++;
            push @junk_list, sprintf('%-40s %-12s pass=%s', $stem, "'$hash'", $v->{pass} // '');
            # Never leave an entry with nothing: a junk vector is better than
            # no vector at all, because the entry still says what it is about.
            if ($drop && @{ $d->{vectors} } > 1) { $dropped++; $changed = 1; next }
            push @keep, $v;
            next;
        }

        unless (looks_tagged($hash)) { push @keep, $v; next }
        $tagged++;

        # $dynamic_N$digest  or  $dynamic_N$digest$salt
        my (undef, $tag, @rest) = split /\$/, $hash;
        my $cand = $rest[0] // '';
        $cand .= ':' . $rest[1] if defined $rest[1] && length $rest[1];
        unless (length $cand) { push @keep, $v; next }

        my $by = verified_by($d, $cand, $v->{pass} // '');
        if ($by) {
            printf STDERR "-   %-38s %s -> %s  (%s)\n", $stem,
                substr($hash, 0, 28), substr($cand, 0, 28), $by if $verbose;
            $v->{hash} = $cand;
            $rewrote++;
            $changed = 1;
        }
        else {
            $failed++;
            push @fail_list, sprintf('%-40s %s', $stem, substr($hash, 0, 60));
        }
        push @keep, $v;
    }

    next unless $changed;
    $d->{vectors} = \@keep;
    emit_entry($path, $d) if $apply;
}

