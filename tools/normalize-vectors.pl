#!/usr/bin/perl
#-----------------------------------------------------------------------
#
# Name: normalize-vectors.pl
# Description: put a test vector into the shape every tool here can read, and
#              report the ones that are not vectors at all
# Category: cracking-rosetta curator
#
# Project: cracking-rosetta | Phase: 7 - pre-publication readiness
#
#-----------------------------------------------------------------------
# METHODOLOGY AND WHY THIS EXISTS
#
# WHAT WENT WRONG
#
# The repository's vector convention is a bare digest, with ':salt' appended
# when there is a salt. Some vectors harvested from john instead carry john's
# own ciphertext tag -- "$dynamic_1518$065c78..." and, when salted,
# "$dynamic_1501$<digest>$<salt>". That is a perfectly good john ciphertext
# and unreadable to everything else: hashcat rejects it, mdxfind rejects it,
# and john's own ad-hoc --format=dynamic='EXPR' rejects it too, because the
# tag names a DIFFERENT format from the one being compiled.
#
# The effect was invisible and expensive. derive-expressions.pl requires every
# vector of an entry to fall before it will write an expression, so one tagged
# vector sank an entry whose other vectors were fine, and the entry came out
# the far end as "john states this expression and it does not reproduce our
# data" -- an open question about an algorithm, when it was a question about
# a string.
#
# A separate shape is worse: a hash field that is not a hash. The sheet import
# carried through a literal "--" on one entry. Nothing rejected it, because
# the schema asks only for a non-empty string.
#
# WHY IT VERIFIES BEFORE IT WRITES
#
# Rewriting a vector is rewriting evidence. So a normalized candidate is
# offered to a tool the entry ALREADY names at tier vector, pinned to that
# identifier, and is written only if that tool recovers the entry's own
# plaintext from it. If nothing verifies, the entry is reported and left
# exactly as it was: a failure here is a finding about the entry, not a
# license to guess.
#
# Tiers are never touched. Making a vector readable does not prove anything
# new -- it lets the tools that do the proving see it. Run
# derive-expressions.pl and verify-vectors.pl afterwards.
#
# WHY JUNK IS NOT DELETED BY DEFAULT
#
# Dropping a vector destroys the only copy of something a person once typed.
# --drop-junk is required, it never leaves an entry with no vectors at all,
# and both the count and every affected line are printed first.
#
# DEPENDENCIES
#   perl, YAML::XS, tools/lib/RosettaEmit.pm, and the tools it verifies with
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-08-30

