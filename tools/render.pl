# Reduce one tool block to a cell: state plus the identifiers to show.

sub cell {
    my ($e, $tool) = @_;
    my $b = $e->{tools}{$tool};
    return { state => 'unknown', ids => [] } unless $b;

    my @ids = $tool eq 'hashcat' ? @{ $b->{modes} || [] }
            : $tool eq 'mdxfind' ? @{ $b->{types} || [] }
            : $tool eq 'john'    ? (@{ $b->{cpu} || [] }, @{ $b->{gpu} || [] })
            :                      ();

    my $tier = $b->{verified} // 'asserted';

    if ($tool eq 'crack') {
        return { state => (defined $b->{supported} && $b->{supported} ? 'claimed' : 'no'),
                 ids => [] };
    }
    return { state => 'no', ids => [] } if !@ids && $tier eq 'absent';
    return { state => 'unknown', ids => [] } unless @ids;

    my $label = $tool eq 'mdxfind' && $b->{iterations} && $b->{iterations} > 1
              ? [ map { "$_ -i$b->{iterations}" } @ids ]
              : [@ids];
    return { state => ($tier eq 'vector' ? 'proven' : 'claimed'),
             ids => $label, tier => $tier };
}

# same_as($entry) - the relations as one phrase a person can read in a table
# cell. A row that says "md5($p.$s)" twice in a 784-row table is a puzzle; a
# row that says "same as md5-pass-salt (application)" is an answer.
sub same_as {
    my ($e) = @_;
    my @r = @{ $e->{relations} || [] } or return '';
    my %verb = (
        'same-computation'   => 'same as',
        'encodes'            => 'encoding of',
        'input-encoding'     => 'input encoding of',
        'iterates'           => 'iterates',
        'truncates'          => 'truncates',
        'collides-on-subset' => 'collides with',
        'duplicate-of'       => 'duplicate of',
    );
    my @parts;
    for my $rel (sort { ($a->{kind} // '') cmp ($b->{kind} // '')
                     || ($a->{entry} // '') cmp ($b->{entry} // '') } @r) {
        my $v = $verb{ $rel->{kind} // '' } // ($rel->{kind} // '?');
        my $d = $rel->{distinction};
        push @parts, sprintf('%s %s%s', $v, $rel->{entry},
            (defined $d && length $d && $d ne 'none') ? " ($d)" : '');
    }
    return join('; ', @parts);
}

my (%tally, %state_count);
my @out;
for my $e (@rows) {
    my %r = (
        id     => $e->{id},
        name   => $e->{name} // $e->{id},
        alias  => join('; ', @{ $e->{aliases} || [] }),
        expr   => $e->{expression} // '',
        # The tier on the expression, and the fallback wording for a row that
        # has none. The expression has never appeared in the HTML or Markdown
        # tables -- those show name: -- so these follow it into the two
        # machine-consumption views and nowhere else.
        expr_tier  => (ref $e->{expression_proof} eq 'HASH'
                       ? ($e->{expression_proof}{verified} // '') : ''),
        # The same claim in john's own notation, which is NOT always the same
        # string: expression: is hx-style and writes a change of
        # representation as a wrapper -- upper(md5($p)) -- where john writes
        # it as a flavour of the hash function -- MD5($p). Copying the
        # expression column into a --format=dynamic= would hand a reader a
        # syntax error on 48 rows, so the runnable form is published
        # separately rather than left to be reconstructed.
        john_expr  => $e->{john_dynamic_expr} // '',
        denotation => (ref $e->{denotation} eq 'HASH'
                       ? ($e->{denotation}{text} // '') : ''),
        status => $e->{status} // 'ok',
        vecs   => scalar @{ $e->{vectors} || [] },
        # serialization: do the tools agree about the STRING, not just the
        # algorithm? Derived, never asserted -- from reads_in, which
        # verify-vectors.pl measures, and credential, which a curator sets to
        # say two spellings are one credential.
        #
        #   divergent  the entry holds one credential written more than one
        #              way, so a hash in one tool's form must be re-encoded
        #              for the other
        #   shared     one string was proven to load in two or more tools
        #   unknown    nothing has established either way
        #
        # Until this column existed, 197 entries had PROVEN that a single
        # string satisfies both hashcat and john and said so nowhere, and a
        # reader holding one could not tell that from "nobody checked".
        serialization => do {
            my ($shared, %tools) = (0);
            for my $v (@{ $e->{vectors} || [] }) {
                next unless ref $v->{reads_in} eq 'ARRAY';
                my @r = @{ $v->{reads_in} };
                $shared = 1 if @r > 1;      # one string, more than one tool
                $tools{$_} = 1 for @r;
            }
            # divergent needs no credential group: reads_in already proves it.
            # verify-vectors runs every tool against every vector of an entry
            # with every plaintext in the wordlist, so a tool that read none of
            # another tool's strings was given the chance and declined. Two
            # tools that each read something, and never the same something, do
            # not take each other's format.
            #
            # credential: adds the stronger claim -- that the two strings are
            # ONE credential rather than each tool's own example -- which
            # nothing in the strings can establish and only a curator sets.
            # Pairwise agreement is not the question a reader has. They hold
            # one string and want to know whether the other tools take it, so
            # the test is whether SOME vector is read by every tool that reads
            # anything here. scrypt is why: its hashcat vector is read by
            # mdxfind too, which looked like agreement, while john refuses
            # both strings and wants $7$86....NaCl$... of its own.
            my $all = join ',', sort keys %tools;
            $shared = 0;
            for my $v (@{ $e->{vectors} || [] }) {
                next unless ref $v->{reads_in} eq 'ARRAY';
                $shared = 1 if join(',', sort @{ $v->{reads_in} }) eq $all;
            }
              keys(%tools) < 2 ? 'unknown'
            : $shared          ? 'shared'
            :                    'divergent';
        },
        # Which form is PRIMARY. The native form -- what the producing system
        # itself stores -- outranks every tool's rewriting of it, so this is
        # simply which vector is native, if the entry knows. Empty means
        # nobody has said, and on a row whose serialization is 'divergent'
        # that is a live question rather than a shrug: a reader holding one of
        # several strings cannot tell the real credential from a cracker's
        # re-encoding of it. Derived, never asserted -- there is no 'primary'
        # flag in the data to drift out of step with this.
        primary_form => do {
            my ($p) = grep { ($_->{form} // '') eq 'native' }
                      @{ $e->{vectors} || [] };
            $p ? 'native' : '';
        },
        notes  => $e->{notes} // '',
        legacy => join('; ', grep { defined && length }
                        ($e->{legacy}{hashes_org}, $e->{legacy}{hashkiller})),
        # The practitioner columns. Per-tool by design -- see tool_fact above
        # for why there is no merged `salted`.
        hashcat_salted => tool_fact($e->{tools}{hashcat}{modes} || [],
                              \%by_mode, sub { exists $_[0]{salt_type} }),
        # hashcat publishes the fast/slow split itself, which is the
        # distinction a practitioner actually plans around, and it cannot go
        # stale relative to hashcat the way a benchmarked H/s figure on this
        # host's one GPU would.
        hashcat_speed  => (tool_fact($e->{tools}{hashcat}{modes} || [],
                              \%by_mode, sub { $_[0]{slow} })
                           =~ s/^yes$/slow/r =~ s/^no$/fast/r),
        john_salted    => tool_fact([ @{ $e->{tools}{john}{cpu} || [] },
                                      @{ $e->{tools}{john}{gpu} || [] } ],
                              \%by_label, sub { ($_[0]{salt_size} // 0) > 0 }),
        # john's own words for what it can tune, verbatim: "iteration count",
        # "N,r,p", argon2's "t,m,p,type". Several formats on one row can name
        # different costs, so they are joined rather than reduced -- an entry
        # spanning bcrypt and scrypt has two answers and should say so.
        john_work_factor => do {
            my %c;
            for my $l (@{ $e->{tools}{john}{cpu} || [] },
                       @{ $e->{tools}{john}{gpu} || [] }) {
                next unless $by_label{$l};
                my $t = $by_label{$l}{tunable_cost};
                $c{$t} = 1 if defined $t && length $t;
            }
            join('; ', sort keys %c);
        },
        mdxfind_salted => tool_fact($e->{tools}{mdxfind}{types} || [],
                              \%by_type,
                              sub { grep { $_ eq 's' } @{ $_[0]{flags} || [] } }),
        nesting_depth  => (nesting_depth($e->{expression}) // ''),
        category    => $e->{category} // '',
        application => join(' ', grep { defined && length }
                             ($e->{application}, $e->{application_version})),
        # Full edges for machines; one short phrase for people.
        relations   => [ map { { kind        => $_->{kind},
                                 entry       => $_->{entry},
                                 distinction => $_->{distinction} // '',
                                 note        => $_->{note} // '' } }
                         @{ $e->{relations} || [] } ],
        sameas      => same_as($e),
        # Why the tier is what it is. Carried for docs/OPEN-QUESTIONS.md,
        # which is only useful if it can print the reason already recorded on
        # the entry rather than re-deriving a worse one.
        expr_note   => (ref $e->{expression_proof} eq 'HASH'
                        ? ($e->{expression_proof}{note} // '') : ''),
        tool_note   => { map { $_ => ($e->{tools}{$_}{note} // '') }
                         qw(hashcat john mdxfind) },
    );
    ($r{hash_length}, $r{hash_length_basis}) = hash_length($e);

    # Identifiers an entry names that the inventory does not have. Counted
    # rather than silently skipped, because the practitioner columns above go
    # empty on exactly these and a reader is owed the reason.
    $unresolved{hashcat} += grep { !$by_mode{$_} }
                            @{ $e->{tools}{hashcat}{modes} || [] };
    $unresolved{john}    += grep { !$by_label{$_} }
                            (@{ $e->{tools}{john}{cpu} || [] },
                             @{ $e->{tools}{john}{gpu} || [] });
    $unresolved{mdxfind} += grep { !$by_type{$_} }
                            @{ $e->{tools}{mdxfind}{types} || [] };

    for my $t (qw(hashcat john mdxfind crack)) {
        my $c = cell($e, $t);
        $r{$t} = $c;
        $r{cracknote} = $e->{tools}{crack}{note} // '' if $t eq 'crack';
        $state_count{$t}{ $c->{state} }++;
    }
    $tally{ $r{status} }++;
    push @out, \%r;
}

# The export shape of a tombstone: the id, the name it had, where it went, and
# nothing else. Every claim column is empty on purpose -- an empty cell says
# "this row asserts nothing", where 'unknown' would say "nobody has checked",
# which is a statement about an algorithm this row no longer is.
my @tomb_out = map { {
    id     => $_->{id},
    name   => $_->{name} // $_->{id},
    into   => $_->{merged_into} // '',
    sameas => same_as($_),
    notes  => $_->{notes} // '',
} } @tombs;

