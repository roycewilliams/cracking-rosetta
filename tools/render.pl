function focusHash(){
  const want = decodeURIComponent(location.hash.slice(1));
  const note = document.getElementById('note');
  note.className=''; note.textContent='';
  if(!want) return;
  const t = M[want];
  const id = t ? t[0] : want;
  if(t){
