#-----------------------------------------------------------------------
# METHODOLOGY AND WHY THESE CHOICES
#
# ONE FILE PER ALGORITHM IS RIGHT FOR GIT AND WRONG FOR READING
#
# Splitting the data into 784 files bought reviewable diffs, per-algorithm
# blame and path-based CODEOWNERS. It cost the thing the spreadsheet was
# actually good at: opening one page and scanning. This puts that back,
# generated, so nobody has to maintain a table by hand again.
#
# FOUR CELL STATES, NOT TWO
#
# The whole point of the tier column is that "no" and "nobody has looked" are
# different answers, and the old sheet could not tell them apart - a blank cell
# meant either. So a tool cell renders as one of:
#
#   proven    identifiers, verified here by round-trip        (tier vector)
#   claimed   identifiers, asserted or upstream-verified
#   no        the tool genuinely cannot do this               (tier absent)
#   unknown   nobody has said                                 (no block at all)
#
# "unknown" is the gap, and it is deliberately the loudest thing on the page,
# because a gap someone can see is a gap someone might fill.
#
# THE README COUNTER IS UPDATED HERE
#
# README.md carries the algorithm count between <!-- counter --> markers, the
# same trick kens-salty-rainbow uses. Updating it here means the number is a
# by-product of rendering rather than something a person has to remember, and
# it cannot drift from the data the way a hand-typed figure does.
#
# THE HTML CARRIES ITS OWN DATA
#
# The page embeds the rows as JSON and filters client-side. No build step, no
# fetch, no CDN - it works from a file:// URL, from GitHub Pages, and from a
# checkout on a machine with no network. That matters for a reference you might
# want open on a cracking box that is not on the internet.
#
#-----------------------------------------------------------------------
# Generated by Claude Opus 5 on 2026-08-29

