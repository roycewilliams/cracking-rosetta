#!/usr/bin/perl
#-----------------------------------------------------------------------
# Project: cracking-rosetta | Phase: maintenance | Task: upstream suite refresh
#
# Name:        upstream-refresh.pl
# Description: check the four upstream cracking suites for new versions, pull
#              and rebuild the ones this account owns, regenerate the mechanical
#              inventories, and print the DELTA a curator needs to decide what
#              to re-verify. It never touches data/algorithms/ and never moves a
#              tier -- regenerating an inventory is mechanical, promoting a
#              mapping is judgment, and this tool does only the first.
#
# METHODOLOGY, AND WHY IT STOPS WHERE IT DOES
#
#   This repository tracks each tool's upstream TIP, not its releases (README,
#   "What you can depend on"). That policy has a standing cost: every pull can
#   change what a type computes, and until now the pull-build-extract-diff loop
#   was run by hand across many sessions, from memory, with the traps recorded
#   only as prose in CLAUDE.md and STATE.md. This script is that loop, with the
#   traps encoded as guards rather than remembered:
#
#     - mdxfind MUST be built CPU-only. A plain `make` links OpenCL (the
#       Makefile auto-enables it on /usr/include/CL/cl.h), and the resulting
#       binary claims the GPU by default -- which has corrupted data on this
#       host -- AND appends " [GPU]" to 109 of its -h rows, which
#       extract-mdxfind.pl's four-column regex does not match, so a regenerated
#       inventory would SILENTLY lose 109 types. We build with the exact
#       CPU-only invocation and refuse to extract if the marker is present.
#     - The delta is computed by IDENTIFIER, not by line: added / removed /
#       changed modes, types and formats, each cross-referenced against the
#       proven corpus so "what to re-verify" is a list, not a hunch.
#     - Nothing is written into data/tools/ without --write, and nothing is
#       ever written into data/algorithms/. john is REPORT-ONLY, because its
#       tree is royce-owned and this account cannot build it (corpus Rule Zero).
#
# WHAT "THE DELTA" IS
#
#   For each buildable tool: old version -> new version, the upstream commit
#   subjects in between (the behavior-change signal CLAUDE.md tells you to read
#   after a pull), and the inventory diff expressed as identifiers added,
#   removed and changed. Every removed or changed identifier that a tier-`vector`
#   row names is flagged: those are the mappings whose proof the new build may
#   have invalidated, and they are the work the move creates.
#
# DEPENDENCIES
#   Perl core (Getopt::Long, Cwd, Digest::MD5), Text::CSV, and the repo's own
#   RosettaTools (for tool_version). git with the gh credential helper for the
#   pulls, and make/cc/etc. for the builds -- all present on this host. The
#   extractors in tools/ do the actual inventory generation; this orchestrates.
#
# INVOCATION
#   No arguments prints usage and exits 2. See --help.
#
# Generated by Claude Opus 4.8 on 2026-09-22
#-----------------------------------------------------------------------

