# recon_git - fetch (read-only) and report how far behind upstream we are, and
# whether the committed inventory already lags the built binary.
sub recon_git {
    my ($tool, $s, $r) = @_;
    my $c = $s->{clone};
    unless (-d "$c/.git") {
        print "   clone MISSING at $c -- nothing to check\n";
        $r->{error} = 'clone missing';
        return;
    }

    # Read-only fetch over HTTPS with the gh credential helper (SSH is off
    # limits from a session). --tags so `git describe` and availability.pl see
    # new release tags.
    my $log = "$rundir/$tool.fetch.log";
    my $rc = run_logged($log, 120, [git_cmd($c, qw(fetch --tags --quiet))]);
    if ($rc != 0) {
        print "   git fetch FAILED (rc=$rc); see $log. Reporting local state only.\n";
    }

    my $local_desc = git_out($c, qw(describe --tags --always));
    my $up_ref     = git_out($c, qw(rev-parse --abbrev-ref --symbolic-full-name @{u}))
                     || 'origin/HEAD';
    my $up_desc    = git_out($c, 'describe', '--tags', '--always', $up_ref);
    my $behind     = git_out($c, 'rev-list', '--count', "HEAD..$up_ref") // '?';

    $r->{local_desc} = $local_desc;
    $r->{up_desc}    = $up_desc;
    $r->{behind}     = $behind;

    # The committed inventory's version vs the version the on-disk binary
    # reports: a gap here means we already hold a newer binary than the
    # inventory reflects (update --no-build closes it without pulling anything).
    my $inv_ver = inventory_version("$root/$s->{inv}");
    my $bin_ver = (-x $s->{binary}) ? tool_version($tool, $s->{binary}) : undef;
    $r->{inv_ver} = $inv_ver;
    $r->{bin_ver} = $bin_ver;

    printf "   checkout : %s\n", $local_desc // '?';
    printf "   upstream : %s  (%s commit%s ahead)\n",
        $up_desc // '?', $behind, ($behind eq '1' ? '' : 's');
    printf "   inventory: %s   binary now: %s\n",
        $inv_ver // '(none)', $bin_ver // '(unbuilt)';

    if (defined $behind && $behind ne '0' && $behind ne '?') {
        my $subjects = git_out($c, 'log', '--no-merges', '--format=  * %s',
                               "HEAD..$up_ref");
        if ($subjects) {
            print "   upstream commits since our checkout (behavior signal):\n";
            print "$subjects\n";
        }
        $r->{new_commits} = 1;
    } else {
        print "   checkout is up to date with upstream.\n";
    }
    if (defined $inv_ver && defined $bin_ver && $inv_ver ne $bin_ver) {
        print "   >> inventory lags the built binary; 'update --no-build "
            . "--only $tool' regenerates it with no pull.\n";
    }
}

# recon_john - no clone to fetch; compare the installed build against the
# committed inventory and say what the operator must do.
sub recon_john {
    my ($tool, $s, $r) = @_;
    my $bin = tool_path('john', undef);
    my $bin_ver = tool_version('john', $bin);
    my $inv_ver = inventory_version("$root/$s->{inv}");
    $r->{bin_ver} = $bin_ver;
    $r->{inv_ver} = $inv_ver;
    printf "   binary   : %s\n   inventory: %s\n",
        $bin_ver // '(cannot read)', $inv_ver // '(none)';
    if (defined $bin_ver && defined $inv_ver && $bin_ver ne $inv_ver) {
        print "   >> installed john differs from the inventory; "
            . "re-run extract-john.pl (operator rebuilds via newjohn).\n";
        $r->{new_commits} = 1;
    } else {
        print "   inventory matches the installed build.\n";
    }
}

#=======================================================================
# Pull / build
#=======================================================================

sub do_pull {
    my ($tool, $s, $r) = @_;
    return 1 unless $r->{new_commits};            # nothing to pull
    my $c = $s->{clone};
    my $log = "$rundir/$tool.pull.log";
    # --ff-only: a fast-forward or nothing. We never want a merge commit in a
    # mirror of someone else's tree.
    my $rc = run_logged($log, 300,
        [git_cmd($c, qw(pull --ff-only --tags --quiet))]);
    if ($rc != 0) {
        print "   git pull FAILED (rc=$rc); see $log. Skipping build.\n";
        $r->{error} = 'pull failed';
        return 0;
    }
    my $now = git_out($c, qw(describe --tags --always));
    print "   pulled -> $now\n";
    $r->{pulled_to} = $now;
    return 1;
}

sub do_build {
    my ($tool, $s, $r) = @_;
    my $c = $s->{clone};
    my $log = "$rundir/$tool.build.log";
    print "   building (log: $log) ...\n";
    for my $cmd (@{ $s->{build} }) {
        # Each build command runs in the clone dir. Prepend `timeout` so a hung
        # build cannot stall the operator forever.
        my $rc = run_logged($log, $build_timeout,
            ['timeout', $build_timeout, @$cmd], $c, 1);
        if ($rc != 0) {
            print "   build step '@$cmd' FAILED (rc=$rc); see $log.\n";
            print "   (hashpipe: if an archive is missing, run 'make deps' once "
                . "as the operator.)\n" if $tool eq 'hashpipe';
            $r->{error} = 'build failed';
            return 0;
        }
    }
    unless (-x $s->{binary}) {
        print "   build reported success but $s->{binary} is missing.\n";
        $r->{error} = 'binary missing after build';
        return 0;
    }

    # The CPU-only guard for mdxfind: a GPU-linked binary marks 109 -h rows with
    # " [GPU]" that the extractor drops silently. Catch it here, loudly, before
    # it can produce a truncated inventory.
    if ($tool eq 'mdxfind') {
        my $h = qx{$s->{binary} -h 2>&1 </dev/null};
        if ($h =~ /\[GPU\]/) {
            print "   REFUSING to extract: mdxfind was built with OpenCL "
                . "(' [GPU]' present in -h). Rebuild CPU-only.\n";
            $r->{error} = 'mdxfind GPU-linked';
            return 0;
        }
    }
    my $bin_ver = tool_version($tool, $s->{binary});
    print "   built: ", $bin_ver // '(version unread)', "\n";
    $r->{bin_ver} = $bin_ver;
    return 1;
}

#=======================================================================
# Extract to a scratch file and diff against the committed inventory
#=======================================================================

sub do_extract_and_diff {
    my ($tool, $s, $r) = @_;
    my $bin = $s->{binary} // tool_path($tool, undef);
    unless (-x $bin || $tool eq 'john') {
        print "   no binary to extract from ($bin).\n";
        return;
    }

    my $new = "$rundir/$tool.new.yaml";
    my @cmd = map { $_ eq '__BIN__' ? $bin
                  : $_ eq '__OUT__' ? $new
                  : $_ } @{ $s->{extract} };
    my $log = "$rundir/$tool.extract.log";
    print "   extracting inventory -> scratch ...\n";
    my $rc = run_logged($log, $build_timeout, [@cmd]);
    if ($rc != 0 || !-s $new) {
        print "   extract FAILED (rc=$rc); see $log.\n";
        $r->{error} = 'extract failed';
        return;
    }

    my $old = "$root/$s->{inv}";
    my $delta = diff_inventory($old, $new, $s->{idkey});
    $r->{delta} = $delta;
    report_delta($tool, $s, $delta);

    if ($write) {
        # Overwrite the committed inventory. This is the only file this script
        # writes into the repo, and only in data/tools/, the mechanical layer.
        require File::Copy;
        File::Copy::copy($new, $old) or die "cannot install $old: $!\n";
        print "   --write: installed $s->{inv} (review 'git diff' before commit)\n";
    } else {
        print "   (scratch inventory kept at $new; pass --write to install it)\n";
    }
}

# diff_inventory - compare two inventory YAMLs by IDENTIFIER, not by line.
#
# Records begin at a line matching /^  - /. Each record's stable id is the
# idkey field (mode number, eN index, or quoted label); its name (where it has
# one) is carried for the report and for the corpus cross-reference. Returns a
# hashref: added / removed (arrayrefs of {id,name}) and changed (arrayref of
# {id,name,name_old,renamed}).
sub diff_inventory {
    my ($old_file, $new_file, $idkey) = @_;
    my $old = parse_records($old_file, $idkey);
    my $new = parse_records($new_file, $idkey);

    my (@added, @removed, @changed);
    for my $id (sort keys %$new) {
        if (!exists $old->{$id}) {
            push @added, { id => $id, name => $new->{$id}{name} };
        } elsif ($old->{$id}{text} ne $new->{$id}{text}) {
            my $renamed = defined $new->{$id}{name}
                       && defined $old->{$id}{name}
                       && $new->{$id}{name} ne $old->{$id}{name};
            push @changed, {
                id       => $id,
                name     => $new->{$id}{name},
                name_old => $old->{$id}{name},
                renamed  => $renamed,
            };
        }
    }
    for my $id (sort keys %$old) {
        push @removed, { id => $id, name => $old->{$id}{name} }
            unless exists $new->{$id};
    }
    return { added => \@added, removed => \@removed, changed => \@changed };
}

# parse_records - id -> { name, text } for one inventory file.
sub parse_records {
    my ($file, $idkey) = @_;
    open my $fh, '<', $file or die "cannot read $file: $!\n";
    my %rec;
    my @cur;                                      # current record's lines
    my $flush = sub {
        return unless @cur;
        my $text = join('', @cur);
        my ($id, $name);
        if    ($idkey eq 'mode')  { ($id)   = $text =~ /^\s*-\s*mode:\s*(\d+)/m }
        elsif ($idkey eq 'index') { ($id)   = $text =~ /^\s*-\s*index:\s*"([^"]+)"/m }
        elsif ($idkey eq 'label') { ($id)   = $text =~ /^\s*-\s*label:\s*"([^"]+)"/m }
        ($name) = $text =~ /^\s+name:\s*"([^"]*)"/m;    # mdxfind/hashpipe/hashcat
        $name //= $id if $idkey eq 'label';            # john's id IS its name
        @cur = ();
        return unless defined $id;
        $rec{$id} = { name => $name, text => $text };
    };
    while (my $line = <$fh>) {
        if ($line =~ /^  - /) { $flush->(); }     # new record boundary
        push @cur, $line if @cur || $line =~ /^  - /;
    }
    $flush->();
    close $fh;
    return \%rec;
}

# report_delta - print the added/removed/changed identifiers and, crucially,
# which proven corpus rows the removed and changed ones touch.
sub report_delta {
    my ($tool, $s, $d) = @_;
    my ($na, $nr, $nc) = (scalar @{$d->{added}}, scalar @{$d->{removed}},
                          scalar @{$d->{changed}});
    printf "   inventory delta: +%d %s, -%d, ~%d changed\n",
        $na, $s->{kind}, $nr, $nc;

    if (!$na && !$nr && !$nc) {
        print "   inventory is identical to the committed copy.\n";
        return;
    }

    my $xref = load_xref($s->{xref});             # identifier -> [proven ids]

    if ($na) {
        print "   ADDED ($s->{kind}s -- new coverage opportunities):\n";
        print_ids($d->{added}, $tool);
    }
    if ($nr) {
        print "   REMOVED ($s->{kind}s no longer in the build):\n";
        print_ids($d->{removed}, $tool);
        flag_proven('REMOVED', $d->{removed}, $xref, $tool);
    }
    if ($nc) {
        print "   CHANGED ($s->{kind}s whose record moved):\n";
        for my $c (@{ $d->{changed} }) {
            my $tag = $c->{renamed}
                    ? " RENAMED '$c->{name_old}' -> '$c->{name}'" : '';
            printf "     %s %s%s\n", $c->{id}, ($c->{name} // ''), $tag;
        }
        flag_proven('CHANGED', $d->{changed}, $xref, $tool);
    }
}

sub print_ids {
    my ($list, $tool) = @_;
    my @show = @$list;
    my $more = 0;
    if (!$verbose && @show > 40) { $more = @show - 40; @show = @show[0..39]; }
    for my $e (@show) {
        printf "     %s %s\n", $e->{id}, ($e->{name} // '');
    }
    print "     ... and $more more (use -v to see all)\n" if $more;
}

# flag_proven - the point of the whole exercise: for each delta identifier,
# name the tier-`vector` rows that depend on it. These are the mappings the
# move may have invalidated -- the re-verification work the pull creates.
sub flag_proven {
    my ($label, $list, $xref, $tool) = @_;
    my @hits;
    for my $e (@$list) {
        # hashcat is keyed by mode number in both inventory and corpus; the two
        # type tools are keyed by NAME in the corpus (the eN index is internal).
        for my $key ($tool eq 'hashcat' ? ($e->{id})
                   : grep { defined } ($e->{name}, $e->{name_old})) {
            next unless defined $key && $xref->{$key};
            push @hits, { key => $key, rows => $xref->{$key} };
        }
    }
    unless (@hits) {
        print "     -> no tier-'vector' rows name these. Nothing to re-verify.\n";
        return;
    }
    print "     -> PROVEN rows to RE-VERIFY (their '$tool' block is tier vector):\n";
    for my $h (@hits) {
        printf "        %-24s <- %s\n", $h->{key}, join(', ', @{ $h->{rows} });
    }
}

# load_xref - build identifier -> [row id, ...] from dist/rosetta.csv, limited
# to rows whose <tool>_state is 'proven'. Text::CSV because the notes column
# carries commas and quotes.
sub load_xref {
    my ($cols) = @_;
    my $csv_file = "$root/dist/rosetta.csv";
    return {} unless -r $csv_file;
    require Text::CSV;
    my $csv = Text::CSV->new({ binary => 1 });
    open my $fh, '<:encoding(utf8)', $csv_file or return {};
    my $hdr = $csv->getline($fh);
    $csv->column_names(@$hdr);
    my %map;
    while (my $row = $csv->getline_hr($fh)) {
        next unless ($row->{ $cols->{state} } // '') eq 'proven';
        my $ids = $row->{ $cols->{id} } // '';
        for my $id (split /[,\s]+/, $ids) {
            next unless length $id;
            push @{ $map{$id} }, $row->{id};
        }
    }
    close $fh;
    return \%map;
}

