# git_cmd / git_out - always with the gh credential helper, always with -C so
# we never chdir into someone else's tree and never run git in the project as
# the wrong user (corpus Rule Zero).
sub git_cmd {
    my ($dir, @args) = @_;
    return ('git', '-c', q{credential.helper=!gh auth git-credential},
            '-C', $dir, @args);
}
sub git_out {
    my ($dir, @args) = @_;
    my @cmd = git_cmd($dir, @args);
    my $out = qx{@{[ map { quote($_) } @cmd ]} 2>/dev/null};
    return undef unless defined $out && $! == 0 || length $out;
    chomp $out;
    return length $out ? $out : undef;
}
sub quote { my $s = shift; $s =~ s/'/'\\''/g; return "'$s'"; }

# run_logged - run a command with stdout+stderr to a log file, return its exit
# code. Optional chdir for the child only (via a fork), optional append. We do
# NOT hand-roll a wait loop: system() waits on the child directly, which cannot
# misfire the way a pgrep poll can (CLAUDE.md, background-jobs).
sub run_logged {
    my ($log, $timeout, $cmd, $chdir, $append) = @_;
    info("exec: @$cmd" . ($chdir ? " (in $chdir)" : ''));
    my $pid = fork();
    die "fork failed: $!\n" unless defined $pid;
    if ($pid == 0) {                              # child
        if ($chdir) { chdir $chdir or die "chdir $chdir: $!\n"; }
        my $mode = $append ? '>>' : '>';
        open STDOUT, $mode, $log or die "open $log: $!\n";
        open STDERR, '>&', \*STDOUT or die "dup: $!\n";
        exec @$cmd;
        die "exec failed: $!\n";
    }
    waitpid($pid, 0);                             # wait on the PID, not a pattern
    return $? >> 8;
}

# inventory_version - the version: field an extractor stamps into an inventory.
sub inventory_version {
    my ($file) = @_;
    return undef unless -r $file;
    open my $fh, '<', $file or return undef;
    while (my $l = <$fh>) {
        return $1 if $l =~ /^version:\s*"([^"]*)"/;
        last if $l =~ /^(?:modes|types|formats):/;   # past the header
    }
    return undef;
}

sub iso_stamp {
    my @t = localtime;                            # localtime: matches the day the operator sees
    return sprintf '%04d%02d%02d-%02d%02d%02d',
        $t[5]+1900, $t[4]+1, $t[3], $t[2], $t[1], $t[0];
}

