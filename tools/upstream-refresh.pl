sub summary {
    my ($rep, $act) = @_;
    print "\n", ('#' x 70), "\n# SUMMARY ($act)\n", ('#' x 70), "\n";
    my $any_new = 0;
    my $any_reverify = 0;
    for my $tool (sort { $SUITE{$a}{order} <=> $SUITE{$b}{order} } keys %$rep) {
        my $r = $rep->{$tool};
        my @bits;
        push @bits, "ERROR: $r->{error}" if $r->{error};
        push @bits, "behind by $r->{behind}"
            if defined $r->{behind} && $r->{behind} ne '0' && $r->{behind} ne '?';
        push @bits, "pulled to $r->{pulled_to}" if $r->{pulled_to};
        if (my $d = $r->{delta}) {
            my $n = @{$d->{added}} + @{$d->{removed}} + @{$d->{changed}};
            push @bits, $n ? "inventory delta $n" : 'inventory unchanged';
            $any_reverify++ if @{$d->{removed}} || @{$d->{changed}};
        }
        $any_new++ if $r->{new_commits};
        printf "  %-9s %s\n", $tool, (@bits ? join('; ', @bits) : 'up to date');
    }
    print "\n";
    if ($act eq 'check') {
        print $any_new
            ? "  New upstream work exists. Run 'update' to pull, build and see "
              . "the inventory delta.\n"
            : "  Everything is current. No action needed.\n";
    } else {
        print "  Inventories regenerated in $rundir.\n";
        print "  Review 'git diff data/tools/' before committing.\n" if $write;
        print "  Nothing was written; re-run with --write to install "
            . "inventories.\n" unless $write;
        print "  >> Some proven rows depend on removed/changed identifiers "
            . "(see above). Re-verify them with tools/verify-vectors.pl before "
            . "trusting their tier.\n" if $any_reverify;
        print "  Curation (data/algorithms/) is deliberately untouched.\n";
    }
}

